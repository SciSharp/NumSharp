        /// <summary>Python's <c>float("nan")</c>: the positive quiet NaN (.NET's <see cref="double.NaN"/> is the negative
        ///     one).</summary>
        private static readonly double PositiveNaN = BitConverter.Int64BitsToDouble(0x7FF8000000000000);

        /// <summary>
        ///     The generator's tie-heavy line: kind 0 small integers with signed zeros, 1 integers only, 2 signed zeros and
        ///     NaN of both signs, 3 an organ pipe with zeros (median-of-3's adversary), 4 three values (heavy ties).
        /// </summary>
        /// <param name="n">The length.</param>
        /// <param name="kind">The kind (0-4).</param>
        /// <returns>The float64 line, bit for bit the Python generator's.</returns>
        private static double[] Line(int n, int kind)
        {
            double[] kind2 = { 0.0, -0.0, 1.0, -1.0, PositiveNaN, -PositiveNaN, 0.0, -0.0, 2.0, -2.0, 0.0 };
            var a = new double[n];
            for (int i = 0; i < n; i++)
            {
                double v;
                switch (kind)
                {
                    case 0:
                        v = (i * 7919L + 13) % 97 % 5 - 2;
                        if (v == 0.0 && i * 31L % 3 == 0) v = -0.0;
                        break;
                    case 1:
                        v = (i * 7919L + 13) % 97 % 7;
                        break;
                    case 2:
                        v = kind2[(i * 7919L + 13) % 11];
                        break;
                    case 3:
                        int h = n / 2;
                        v = (double)(i < h ? i : n - 1 - i) % 50 - 10;
                        if (v == 0.0 && i % 2 == 1) v = -0.0;
                        break;
                    default:
                        v = i * 2654435761L % 3 - 1.0;
                        if (v == 0.0 && i % 5 < 2) v = -0.0;
                        break;
                }
                a[i] = v;
            }
            return a;
        }

        /// <summary>The generator's array of a case: the line in the case's dtype (complex: the line as the real part, the
        ///     next kind's line as the imaginary part; bool: the line's nonzero test).</summary>
        /// <param name="dtype">NumPy's dtype name.</param>
        /// <param name="kind">The line kind.</param>
        /// <param name="n">The length.</param>
        /// <returns>The array.</returns>
        private static NDArray Build(string dtype, int kind, int n)
        {
            var line = Line(n, kind);
            switch (dtype)
            {
                case "complex128":
                {
                    var im = Line(n, (kind + 1) % 5);
                    var c = new Complex[n];
                    for (int i = 0; i < n; i++) c[i] = new Complex(line[i], im[i]);
                    return np.array(c);
                }
                case "bool":
                {
                    var b = new bool[n];
                    for (int i = 0; i < n; i++) b[i] = line[i] != 0.0;
                    return np.array(b);
                }
                case "float32": return np.array(line).astype(NPTypeCode.Single);
                case "float16": return np.array(line).astype(NPTypeCode.Half);
                case "int64": return np.array(line).astype(NPTypeCode.Int64);
                case "int32": return np.array(line).astype(NPTypeCode.Int32);
                default: return np.array(line);
            }
        }

        /// <summary>The upper-case hex SHA-256 of an array's C-order bytes.</summary>
        /// <param name="a">The array.</param>
        /// <returns>The digest.</returns>
        private static string Sha(NDArray a) => Convert.ToHexString(SHA256.HashData(a.tobytes()));

        /// <summary>
        ///     np.partition and np.argpartition of every case at its kth list: the bytes NumPy 2.4.2 returns (values with
        ///     their zero signs and NaN bits, and the tied indices).
        /// </summary>
        [TestMethod]
        public void MultiKth_PartitionAndArgPartition_AreNumPysBytes()
        {
            var failures = new System.Collections.Generic.List<string>();
            foreach (var (dtype, kind, n, kth, partition, argPartition) in Cases)
            {
                using var a = Build(dtype, kind, n);
                using var p = np.partition(a, kth);
                using var ap = np.argpartition(a, kth);
                string tag = $"{dtype} kind {kind} n {n} kth [{string.Join(", ", kth)}]";
                if (Sha(p) != partition) failures.Add("partition " + tag);
                if (Sha(ap) != argPartition) failures.Add("argpartition " + tag);
            }
            failures.Should().BeEmpty("every case is NumPy 2.4.2's introselect_ arrangement");
        }

        /// <summary>
        ///     The quantile family over signed zeros, every method: the bits NumPy 2.4.2 returns (its partition at its own
        ///     kth list decides which zero each neighbour reads), and the nan forms after <c>_remove_nan_1d</c>'s reorder.
        /// </summary>
        [TestMethod]
        public void QuantileFamily_OverSignedZeros_AreNumPysBits()
        {
            var failures = new System.Collections.Generic.List<string>();
            foreach (var (fn, kind, n, q, method, bits) in QuantileCases)
            {
                var line = Line(n, kind);
                if (fn == "nanquantile")
                    for (int i = 0; i < n; i += 7) line[i] = PositiveNaN;
                using var a = np.array(line);
                using var r = fn == "nanquantile" ? np.nanquantile(a, q, method: method) : np.quantile(a, q, method: method);
                string got = Convert.ToHexString(r.tobytes());
                if (got != bits) failures.Add($"{fn} kind {kind} n {n} q {q} {method}: {got} (NumPy {bits})");
            }
            failures.Should().BeEmpty("every case is NumPy 2.4.2's bits");
        }

