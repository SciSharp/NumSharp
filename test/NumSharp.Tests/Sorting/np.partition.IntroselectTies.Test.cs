    /// <summary>
    ///     The QB43 gate: np.partition / np.argpartition at SEVERAL kth, and the quantile family, arrange EQUAL values
    ///     exactly as NumPy 2.4.2's <c>introselect_</c> does, which several kth run on every host. Every expectation is
    ///     NumPy's own: the SHA-256 of its partition / argpartition bytes and the bits of its quantiles, over lines a
    ///     formula builds on both sides (no data embedded). The lines are tie-heavy (signed zeros, a few repeated values,
    ///     NaN of both signs) and long enough to reach every part of the select: dumb_select, the inexact last-maximum
    ///     pass, median-of-3 with the Hoare scan, the block partition (lines past ~260 elements), median-of-medians-5 (the
    ///     organ pipe), and the pivot stack across 2-5 kth.
    /// </summary>
    /// <remarks>
    ///     Generated by <c>gen_unit_expectations.py</c> (QB43 session, NumPy 2.4.2): <c>line(n, kind)</c> below is its
    ///     <c>line</c>. A failing hash names the dtype, the line kind, the length and the kth list; the session's
    ///     differential fuzzer (45,000 random cases plus 1,828 adversarial ones) is the broader gate this file pins.
    /// </remarks>
    [TestClass]
    public class NpPartitionIntroselectTiesTests
