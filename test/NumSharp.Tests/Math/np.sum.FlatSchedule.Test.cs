    /// <summary>
    ///     The FLAT <c>np.sum</c> / <c>np.mean</c> of a float loop is NumPy's add.reduce bit for bit: the result starts at
    ///     the identity +0.0, the reduce iterator hands the add loop the operand in inner-loop CALLS, and each call does
    ///     <c>*out += pairwise_sum(call)</c>. Which elements share a call is NpyIter's schedule — the axes sorted by
    ///     |stride| and coalesced signed, then one call per run in place or buffered fills of whole runs (never across an
    ///     outer block), and fills of <c>np.getbufsize()</c> elements for a CAST operand — so it decides the last bits.
    ///     Every expectation here is NumPy 2.4.2's raw result for the same call.
    /// </summary>
    /// <remarks>
    ///     <para>
    ///     The operands are order-sensitive on purpose: <see cref="Ramp"/> spreads its values over ~120 binades
    ///     (float64; ~60 for float32), so a sum is exact in no order and every call boundary moves the last bits. Before the
    ///     exact engine the flat route summed with four SIMD accumulators, which agreed with NumPy only when every partial
    ///     sum happened to be exact; the oracle's summation-order excuse hid the difference.
    ///     </para>
    ///     <para>
    ///     The expectations were generated by running NumPy on the same formulas (Python's <c>np.ldexp</c> of the same
    ///     integer ramps); the formulas only produce values that every dtype holds exactly, so the operands are identical
    ///     on both sides.
    ///     </para>
    /// </remarks>
    [TestClass]
    public class np_sum_flat_schedule_tests
    {
        /// <summary>
        ///     The test operand: element i is <c>((i·7919) mod 1000 − 500)·2^e</c>, with <c>e = (i·13) mod 121 − 60</c>
        ///     for float64 / complex128 (the imaginary part is element i + 17) and <c>(i·13) mod 61 − 30</c> for float32 —
        ///     integers times powers of two, exact in the dtype and spread wide enough that no sum is exact. float16 takes
        ///     <see cref="SmallRamp"/> (|v| ≤ 800, zero mean over every 1407 elements, so long sums stay finite); int32 /
        ///     int64 <c>(i·7919) mod 2001 − 1000</c>, uint8 <c>(i·7919) mod 251</c>, bool <c>(i·7919) mod 3 = 1</c>.
        /// </summary>
        /// <param name="n">The element count.</param>
        /// <param name="dtype">float64, float32, float16, complex128, int32, int64, uint8 or bool.</param>
        /// <returns>A fresh 1-D C-contiguous array.</returns>
        /// <exception cref="ArgumentException">Any other dtype.</exception>
        private static NDArray Ramp(int n, DType dtype)
        {
            switch (dtype.GetTypeCode())
            {
                case NPTypeCode.Double:
                {
                    var v = new double[n];
                    for (long i = 0; i < n; i++) v[i] = WideValue(i, 121, 60);
                    return np.array(v);
                }
                case NPTypeCode.Single:
                {
                    var v = new float[n];
                    for (long i = 0; i < n; i++) v[i] = (float)WideValue(i, 61, 30);
                    return np.array(v);
                }
                case NPTypeCode.Half:
                    return SmallRamp(n, np.float16);
                case NPTypeCode.Complex:
                {
                    var v = new System.Numerics.Complex[n];
                    for (long i = 0; i < n; i++)
                        v[i] = new System.Numerics.Complex(WideValue(i, 121, 60), WideValue(i + 17, 121, 60));
                    return np.array(v);
                }
                case NPTypeCode.Int32:
                {
                    var v = new int[n];
                    for (long i = 0; i < n; i++) v[i] = (int)((i * 7919) % 2001 - 1000);
                    return np.array(v);
                }
                case NPTypeCode.Int64:
                {
                    var v = new long[n];
                    for (long i = 0; i < n; i++) v[i] = (i * 7919) % 2001 - 1000;
                    return np.array(v);
                }
                case NPTypeCode.Byte:
                {
                    var v = new byte[n];
                    for (long i = 0; i < n; i++) v[i] = (byte)((i * 7919) % 251);
                    return np.array(v);
                }
                case NPTypeCode.Boolean:
                {
                    var v = new bool[n];
                    for (long i = 0; i < n; i++) v[i] = (i * 7919) % 3 == 1;
                    return np.array(v);
                }
                default:
                    throw new ArgumentException($"no ramp for {dtype}", nameof(dtype));
            }

            // ((i·7919) mod 1000 − 500)·2^((i·13) mod span − bias): exact in float64 (and in float32 for span 61).
            static double WideValue(long i, int span, int bias)
                => System.Math.ScaleB((i * 7919) % 1000 - 500, (int)((i * 13) % span - bias));
        }

        /// <summary>
        ///     The float16-sized operand: <c>((i·7919) mod 201 − 100)·2^((i·13) mod 7 − 3)</c>, exact in float16 — so a
        ///     float64 array of it can be summed in a float16 loop without overflowing.
        /// </summary>
        /// <param name="n">The element count.</param>
        /// <param name="dtype">The dtype the values are converted to (exactly).</param>
        /// <returns>A fresh 1-D C-contiguous array.</returns>
        private static NDArray SmallRamp(int n, DType dtype)
        {
            var v = new double[n];
            for (long i = 0; i < n; i++)
                v[i] = System.Math.ScaleB((i * 7919) % 201 - 100, (int)((i * 13) % 7 - 3));
            return np.array(v).astype(dtype);
        }

        /// <summary>
        ///     An AXIS that leaves ONE output — a 1-D operand's only axis, or an axis whose siblings all have extent 1 — is
        ///     the flat reduction in NumPy (its iterator drops the extent-1 axes), so a cast loop runs the flat schedule:
        ///     fills of <c>np.getbufsize()</c> elements, <c>*out += pairwise_sum(fill)</c> each. The axis routes summed the
        ///     whole cast copy in one pairwise call instead, and walked a REVERSED axis in memory order even without a cast
        ///     (plan <c>docs/plans/api-parameter-parity.md</c>, item X5); the forward no-cast case was already right and
        ///     stays as a guard. Every expectation is NumPy 2.4.2's result for the same
        ///     call on the same ramp.
        /// </summary>
        [TestMethod]
        public void Sum_AxisLeavingOneOutput_RunsTheFlatSchedule()
        {
            var fails = new List<string>();
            const string f32 = "float32 () 6233ce6c";
            Check(fails, "sum float64 1-D axis 0 dtype=float32", () => np.sum(Ramp(20000, np.float64), 0, np.float32), f32);
            Check(fails, "sum float64 1-D axis -1 keepdims dtype=float32", () => np.sum(Ramp(20000, np.float64), -1, true, np.float32), "float32 (1,) 6233ce6c");
            Check(fails, "sum float64 (n,1) axis 0 dtype=float32", () => np.sum(Ramp(20000, np.float64).reshape(20000, 1), 0, np.float32), "float32 (1,) 6233ce6c");
            Check(fails, "sum float64 (1,n) axis 1 keepdims dtype=float32", () => np.sum(Ramp(20000, np.float64).reshape(1, 20000), 1, true, np.float32), "float32 (1,1) 6233ce6c");
            Check(fails, "sum float64 (1,n,1) axis -2 dtype=float32", () => np.sum(Ramp(20000, np.float64).reshape(1, 20000, 1), -2, np.float32), "float32 (1,1) 6233ce6c");
            Check(fails, "sum float64 [::2] axis 0 dtype=float32", () => np.sum(Ramp(40000, np.float64)["::2"], 0, np.float32), "float32 () e0235140");
            Check(fails, "sum float64 reversed axis 0 dtype=float32", () => np.sum(Ramp(30000, np.float64)["::-1"], 0, np.float32), "float32 () e293ec22");
            Check(fails, "sum float32 1-D axis 0 dtype=float64", () => np.sum(Ramp(20000, np.float32), 0, np.float64), "float64 () 426a98b40852fbf0");
            Check(fails, "sum float32 (n,1) axis 0 dtype=float16 (overflows to NaN)", () => np.sum(Ramp(20000, np.float32).reshape(20000, 1), 0, np.float16), "float16 (1,) nan");
            Check(fails, "sum float16 1-D axis 0 dtype=float32", () => np.sum(Ramp(20000, np.float16), 0, np.float32), "float32 () 44563800");
            Check(fails, "sum complex128 1-D axis 0 dtype=float64", () => np.sum(Ramp(20000, np.complex128), 0, np.float64), "float64 () 444679cd12d6ca8a");
            Check(fails, "sum float64 1-D axis 0 dtype=complex128", () => np.sum(Ramp(20000, np.float64), 0, np.complex128), "complex128 () 444679cd12d6ca8e 0000000000000000");
            Check(fails, "sum int32 1-D axis 0 dtype=float16", () => np.sum(Ramp(20000, np.int32), 0, np.float16), "float16 () 6d33");
            Check(fails, "sum float64 1-D axis 0 (no cast: already right)", () => np.sum(Ramp(20000, np.float64), 0), "float64 () 444679cd12d6ca88");
            // A REVERSED axis without a cast: NumPy walks it in logical order (DONT_NEGATE_STRIDES) — axis=None's values.
            Check(fails, "sum float64 reversed axis 0 (no cast)", () => np.sum(Ramp(30000, np.float64)["::-1"], 0), "float64 () c4527d846302e4ff");
            Check(fails, "sum float32 reversed axis 0 (no cast)", () => np.sum(Ramp(30000, np.float32)["::-1"], 0), "float32 () 53365e0a");
            Check(fails, "sum complex128 reversed axis 0 (no cast)", () => np.sum(Ramp(30000, np.complex128)["::-1"], 0), "complex128 () c4527d846302e4fa c4520b0fa2bc75bd");
            AssertNoMismatch(fails, "an axis that leaves one output runs NumPy's flat schedule, buffer fills of a cast loop included");
        }

