        // =============================================================================
        // ClipNDArray — np.clip dispatcher
        // =============================================================================
        //
        // This class only handles policy, ported from numpy/_core/_methods.py::_clip and from
        // the argument handling of the ufunc that function routes to:
        //   1. _clip's drop rule: on an integer array, a Python-int bound at or past the
        //      dtype's limit cannot clip any element, so it is dropped (None);
        //   2. routing: no bound left → positive, one → minimum / maximum, two → clip. The
        //      routed name is the one NumPy's cast errors quote;
        //   3. the loop dtype (dtype= or NEP-50 weak-scalar promotion), the Python-int packing
        //      check (OverflowError, never a wrap), the dtype= input casts and the out= cast
        //      rule (same_kind), in NumPy's error order;
        //   4. deciding whether bounds are scalar vs array, and contiguity gating.
        // The actual element-wise loop is generated by
        // DirectILKernelGenerator.Clip as a DynamicMethod and cached per
        // (dtype, mode, kind). No SIMD width is hardcoded — the kernel adapts
        // to V128 / V256 / V512 via GetVectorContainerType().
        //
        // Two execution paths, no materializing copy for non-contiguous input:
        //   * Contiguous fast path — every operand C-contiguous offset-0 → the IL
        //     kernel (SIMD where the dtype supports it) in one src→dst pass.
        //   * Strided path (ClipStrided) — strided / transposed / sliced / F-order /
        //     broadcast (stride=0) operands are read through their own strides in
        //     C-order via FlatStrideOffset, writing a fresh C-contiguous result. Its
        //     per-element clamp mirrors the IL kernel's NaN-propagating semantics
        //     exactly (incl. the signed-zero tie), so both paths agree bit-for-bit.
        //   A dtype change still goes through Cast (a genuine conversion), and a
        //   non-C-contiguous @out is relayed with copyto (writing a strided output
        //   is inherent, not a kernel-dodge copy).
        // =============================================================================

        /// <summary>
        /// np.clip's engine entry: NumPy's <c>_methods._clip</c> plus the ufunc it routes to. A Python-int
        /// bound that cannot clip anything is dropped. A kept bound that does not fit the loop dtype raises
        /// <see cref="OverflowException"/> instead of wrapping. All other bounds clip through the IL kernel.
        /// </summary>
        /// <param name="lhs">The array to clip. Any layout; it is read through its own strides.</param>
        /// <param name="min">The lower bound, or null for none. A 0-d bound is a scalar. A 0-d bound of an
        /// integer dtype (any of the eight C# integer primitives, or char) is NumPy's Python int, because
        /// a C# integer literal arrives as one. An array bound (ndim ≥ 1) broadcasts to <paramref name="lhs"/>.</param>
        /// <param name="max">The upper bound, or null for none, with the same scalar rules as <paramref name="min"/>.</param>
        /// <param name="dtype">The loop dtype (NumPy's <c>dtype=</c>). It replaces the promoted dtype, and every input
        /// must reach it by a same_kind cast. The drop rule still uses <paramref name="lhs"/>'s own range.</param>
        /// <param name="out">The array to write into, or null for a fresh result. The loop dtype must reach it by a
        /// same_kind cast. Its shape must equal <paramref name="lhs"/>'s. It is returned as-is.</param>
        /// <returns>The clipped array: <paramref name="out"/> when given, otherwise a fresh array of the loop dtype.</returns>
        /// <exception cref="ValueError"><paramref name="out"/> is read-only (checked first, as in NumPy).</exception>
        /// <exception cref="OverflowException">A kept Python-int bound does not fit an integer loop dtype
        /// ("Python integer 1000 out of bounds for int8"), raised before any element is read, so also for an
        /// empty <paramref name="lhs"/>. See <see cref="NDExprTypeRules.CheckPyIntPacksIntoLoop"/>.</exception>
        /// <exception cref="TypeError">No bound is left and the loop would be bool: NumPy's <c>positive</c> has no bool loop.</exception>
        /// <exception cref="ArgumentException">A <paramref name="dtype"/> the inputs cannot reach, or a loop dtype
        /// <paramref name="out"/> cannot hold, under the same_kind rule (NumPy's UFuncTypeError texts, naming the routed
        /// ufunc), or an <paramref name="out"/> of another shape.</exception>
        [NDScoped]
        public override unsafe NDArray ClipNDArray(NDArray lhs, NDArray min, NDArray max, DType dtype = null, NDArray @out = null)
        {
            NPTypeCode? typeCode = dtype?.GetTypeCode();

            // ---- @out writeability FIRST: NumPy's out converter refuses a read-only out before any
            //      operand is converted, so it wins even over the Python-int OverflowError below (probed
            //      2.4.2: clip(int8, 1000, 2000, out=read_only) reports "output array is read-only").
            if (@out is not null)
                NumSharpException.ThrowIfNotWriteable(@out.Shape);

            // ---- numpy/_core/_methods.py::_clip, block 1. On an integer array a Python-int bound at or
            //      past the dtype's limit cannot clip any element, so NumPy drops it (sets it to None)
            //      before the ufunc runs. Kept, it would have to be packed into the array's dtype, where it
            //      does not fit. That gap is the old silent wrap: clip(uint8, 0, 256) packed 256 as 0 and
            //      returned all zeros, where NumPy returns the array unchanged.
            DropUnclippingPyIntBounds(lhs.GetTypeCode, ref min, ref max);

            // ---- _clip, block 2: route. No bound left → um.positive(a, out=out, **kwargs), which is a
            //      typed copy with positive's own rules (no bool loop, 'positive' in every cast error).
            if (min is null && max is null)
            {
                ValidatePositiveLoop(lhs.GetTypeCode, typeCode);
                NPTypeCode copyType = typeCode ?? lhs.GetTypeCode;
                if (@out is not null)
                {
                    ValidateOutCast(copyType, @out.GetTypeCode, "positive");
                    if (@out.Shape != lhs.Shape)
                        throw new ArgumentException($"@out's shape ({@out.Shape}) must match lhs's shape ({lhs.Shape}).'");
                }

                // Cast keeps the input's memory order (K), as positive's output does in NumPy: a permuted
                // input stays permuted, a broadcast input becomes a fresh writeable C array.
                if (@out is null) return Cast(lhs, copyType, copy: true);
                np.copyto(@out, Cast(lhs, copyType, copy: false));
                return @out;
            }

            // One bound left → um.minimum / um.maximum, both → um.clip. NumPy's cast errors name the routed
            // ufunc, so clip(int8, -1000, 50, dtype=uint8) reports "ufunc 'minimum' input 0".
            string ufunc = min is null ? "minimum" : max is null ? "maximum" : "clip";

            // ---- Loop dtype: an explicit `dtype=` wins; otherwise NEP-50 promotion of lhs with the bounds.
            NPTypeCode outType = typeCode ?? PromoteClipBound(PromoteClipBound(lhs.typecode, min), max);

            // ---- NEP 50: each kept Python-int bound is packed into the loop dtype, which raises rather than
            //      wraps. NumPy does it while resolving descriptors, so it precedes every cast check below
            //      (probed: clip(int8, -1, 5, dtype=uint64) reports the -1, not the int8->uint64 input cast).
            //      Operand order: min, then max.
            CheckPyIntBoundPacks(min, outType);
            CheckPyIntBoundPacks(max, outType);

            // ---- dtype=: every input must reach the requested loop by a same_kind cast (validate_casting).
            if (typeCode.HasValue)
                ValidateClipInputCasts(lhs, min, max, outType, ufunc);

            // ---- @out: the cast rule before the shape — NumPy resolves dtypes, then builds the iterator.
            //      A same_kind-reachable out of another dtype is legal: the loop runs at outType and the
            //      result is cast into out (np.clip(uint8, 5, 100, out=int8) is NumPy-legal).
            bool outNeedsCast = false;
            if (@out is not null)
            {
                ValidateOutCast(outType, @out.GetTypeCode, ufunc);
                if (@out.Shape != lhs.Shape)
                    throw new ArgumentException($"@out's shape ({@out.Shape}) must match lhs's shape ({lhs.Shape}).'");
                outNeedsCast = @out.GetTypeCode != outType;
            }

            // Boundary scope: the bound casts, dtype-converted source, NaN fill and any relay
            // buffer are reclaimed at exit; the yielded result (or the caller's untracked @out)
            // is the only survivor.

            // ---- Empty input — nothing to compute. Every check above still ran, as in NumPy, where
            //      clip(empty int8, 1000, 2000) raises the OverflowError.
            if (lhs.size == 0)
                return @out ?? Cast(lhs, outType, copy: true);

            // ---- Special-case NaN scalar bounds on float32/float64 (NumPy: entire
            //      result is NaN). The IL kernel uses Vector.Min/Max which on x86
            //      do not propagate NaN-in-bounds in the second-operand position
            //      consistently across vendors, so we short-circuit here.
            //      Single/Double ONLY — a && bound tighter than || here once made ANY
            //      dtype with a NaN max-bound take this float32 fill (a Half array came
            //      back as a float32 all-NaN — wrong dtype AND payload). Half now rides
            //      its bit-level clip kernel, which propagates the bound's exact NaN
            //      bits per element like NumPy's _NPY_MIN/_NPY_MAX chain (probed 2.4.2:
            //      clip(5f16, 1, nan) = the bound's NaN bits, not a canonical fill).
            if ((outType == NPTypeCode.Single || outType == NPTypeCode.Double)
                && (ScalarIsNaN(min) || ScalarIsNaN(max)))
            {
                var nan = outType == NPTypeCode.Double
                    ? np.full(lhs.Shape, double.NaN)
                    : np.full(lhs.Shape, float.NaN);
                if (@out is null) return nan;
                np.copyto(@out, nan);
                return @out;
            }

            // ---- Decide bound kinds and route through DirectILKernelGenerator
            bool minScalar = min is null || min.ndim == 0;
            bool maxScalar = max is null || max.ndim == 0;
            bool allScalarBounds = minScalar && maxScalar;

            // Build dispatch tuple for the IL kernel
            DirectILKernelGenerator.ClipMode mode =
                min is null ? DirectILKernelGenerator.ClipMode.MaxOnly :
                max is null ? DirectILKernelGenerator.ClipMode.MinOnly :
                              DirectILKernelGenerator.ClipMode.BothBounds;
            DirectILKernelGenerator.ClipBoundsKind kind =
                allScalarBounds ? DirectILKernelGenerator.ClipBoundsKind.Scalar
                                : DirectILKernelGenerator.ClipBoundsKind.Array;

            // Cast bounds to outType. For scalar (0-d) bounds astype is O(1);
            // for array bounds it's broadcast_to(target_shape) + astype, with
            // the same-shape/same-dtype short-circuit handled by PrepareBound.
            NDArray loCast = null, hiCast = null;
            if (kind == DirectILKernelGenerator.ClipBoundsKind.Scalar)
            {
                // ScalarBoundReady avoids the astype CLONE when the bound is already a
                // contiguous offset-0 scalar of outType (the dominant np.clip(arr, lo, hi)
                // case where lo/hi arrive as same-dtype scalars) — RunClipKernel reads the
                // value through .Address, which is only correct at offset 0. Measured ~0.9µs
                // saved per scalar bound at small N (the astype path's dominant cost there).
                if (min is not null) loCast = ScalarBoundReady(min, outType) ? min : min.astype(outType);
                if (max is not null) hiCast = ScalarBoundReady(max, outType) ? max : max.astype(outType);
            }
            else
            {
                loCast = PrepareBound(min, lhs.Shape, outType);
                hiCast = PrepareBound(max, lhs.Shape, outType);
            }

            // ---- Pick src and route to the contiguous IL kernel or the strided loop
            bool arrayBounds = kind == DirectILKernelGenerator.ClipBoundsKind.Array;

            // src at outType. Cast performs only a genuine dtype change; the source LAYOUT is
            // preserved (no contiguity copy). Strided / F-order / sliced views are read through
            // their strides by the strided path below — the previous code materialized a C-order
            // copy here (and a second copy('C') for array bounds), the rejected anti-pattern.
            NDArray srcArr = lhs.GetTypeCode == outType ? lhs : Cast(lhs, outType, copy: true);

            bool srcFlat = srcArr.Shape.IsContiguous && srcArr.Shape.Offset == 0;
            // The flat IL kernel walks src/dst/lo/hi linearly and pairs them by C-order index,
            // so array bounds must also be C-contiguous offset-0; scalar bounds are one value
            // broadcast to every lane and are always fine.
            bool boundsFlat = !arrayBounds
                || ((loCast is null || (loCast.Shape.IsContiguous && loCast.Shape.Offset == 0))
                    && (hiCast is null || (hiCast.Shape.IsContiguous && hiCast.Shape.Offset == 0)));

            // Fresh C-contiguous shape for any allocated result — must NOT inherit lhs's strides
            // (np.empty(lhs.Shape) would clone a strided/F-order layout, which the linear dst
            // writes below would then mis-address).
            Shape cShape = new Shape((long[])lhs.shape.Clone());

            if (srcFlat && boundsFlat)
            {
                // Fast path: every operand plainly C-contiguous — IL kernel (SIMD where the
                // dtype supports it) in a single src→dst pass (or straight into a C-order @out).
                // The kernel writes outType elements, so an @out of another (same_kind-validated)
                // dtype takes the relay too: copyto performs the cast into it.
                if (@out is not null && (!@out.Shape.IsContiguous || @out.Shape.Offset != 0 || outNeedsCast))
                {
                    var tmp = np.empty(cShape, outType);
                    RunClipKernel(srcArr, tmp, loCast, hiCast, outType, mode, kind);
                    np.copyto(@out, tmp);    // relay the C-order result into the strided / other-dtype @out
                    return @out;
                }
                var dstFast = @out ?? np.empty(cShape, outType);
                RunClipKernel(srcArr, dstFast, loCast, hiCast, outType, mode, kind);
                return dstFast;
            }

            // ---- Strided / F-order src or array bounds: read every operand through its own
            //      strides in C-order, writing a fresh C-contiguous result — no copy. copyto
            //      relays into a non-C-contiguous @out (writing a strided output is inherent).
            // The loop writes outType elements: an @out of another dtype is filled by the copyto relay below.
            NDArray outBuf = (@out is not null && @out.Shape.IsContiguous && @out.Shape.Offset == 0 && !outNeedsCast)
                ? @out
                : np.empty(cShape, outType);
            ClipStrided(srcArr, outBuf, loCast, hiCast, outType, mode, kind);
            if (@out is not null && !ReferenceEquals(outBuf, @out))
            {
                np.copyto(@out, outBuf);
                return @out;
            }
            return outBuf;
        }

        // Extract pointers and invoke the flat IL clip kernel. src/dst (and array bounds) must
        // be C-contiguous offset-0; scalar bounds are single values.
        private static unsafe void RunClipKernel(NDArray src, NDArray dst, NDArray loCast, NDArray hiCast,
            NPTypeCode outType, DirectILKernelGenerator.ClipMode mode, DirectILKernelGenerator.ClipBoundsKind kind)
        {
            void* srcPtr = (void*)src.Address;
            void* dstPtr = (void*)dst.Address;
            void* loPtr  = loCast is null ? null : (void*)loCast.Address;
            void* hiPtr  = hiCast is null ? null : (void*)hiCast.Address;
            DirectILKernelGenerator.Clip(outType, mode, kind, srcPtr, dstPtr, dst.size, loPtr, hiPtr);
        }

        // Strided clip: read src and (array) bounds through their own strides in C-order, writing
        // a C-contiguous dst. Per-element semantics mirror the IL kernel's scalar tail exactly —
        // Math.Max/Min for sized numerics + decimal, NaN-aware helpers for Half / Complex, numeric
        // ordering for Char (read as UInt16), Boolean read as Byte (bool storage is 0/1, so the
        // unsigned Byte Max/Min gives the same false<true ordering as the contiguous path's 0/1
        // scalar-select) — so results are identical to the contiguous path.
        private static unsafe void ClipStrided(NDArray src, NDArray dst, NDArray loCast, NDArray hiCast,
            NPTypeCode outType, DirectILKernelGenerator.ClipMode mode, DirectILKernelGenerator.ClipBoundsKind kind)
        {
            long n = dst.size;
            var dims = dst.shape;
            int ndim = dst.ndim;
            bool needLo = mode != DirectILKernelGenerator.ClipMode.MaxOnly;
            bool needHi = mode != DirectILKernelGenerator.ClipMode.MinOnly;
            bool arr = kind == DirectILKernelGenerator.ClipBoundsKind.Array;

            byte* sBase = (byte*)src.Address + src.Shape.offset * src.dtypesize;
            bool srcC = src.Shape.IsContiguous && src.Shape.offset == 0;
            var srcStr = src.Shape.Strides;

            byte* loBase = loCast is null ? null : (byte*)loCast.Address + loCast.Shape.offset * loCast.dtypesize;
            byte* hiBase = hiCast is null ? null : (byte*)hiCast.Address + hiCast.Shape.offset * hiCast.dtypesize;
            long[] loStr = loCast?.Shape.Strides;
            long[] hiStr = hiCast?.Shape.Strides;
            bool loC = !arr || loCast is null || (loCast.Shape.IsContiguous && loCast.Shape.offset == 0);
            bool hiC = !arr || hiCast is null || (hiCast.Shape.IsContiguous && hiCast.Shape.offset == 0);

            // float32/float64 with two scalar bounds take NumPy's CONST fast path (clip.cpp
            // _npy_clip_const_minmax_): x < lo ? lo : x, then x > hi ? hi : x — a tie keeps the element.
            // The contiguous IL kernel makes the same switch (DirectILKernelGenerator.UsesConstSelect),
            // so clip(-0.0, 0, 1) is -0.0 on every layout.
            bool constSelect = !arr && needLo && needHi;
            if (constSelect && outType == NPTypeCode.Single)
            {
                ClipStridedT<float>(sBase, (float*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi,
                    &DirectILKernelGenerator.FloatClipLowSelect, &DirectILKernelGenerator.FloatClipHighSelect);
                return;
            }
            if (constSelect && outType == NPTypeCode.Double)
            {
                ClipStridedT<double>(sBase, (double*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi,
                    &DirectILKernelGenerator.DoubleClipLowSelect, &DirectILKernelGenerator.DoubleClipHighSelect);
                return;
            }

            switch (outType)
            {
                // Boolean rides the Byte kernel: bool is one byte storing 0/1 (loaded as Ldind_U1
                // by the contiguous IL path), and unsigned Byte Max/Min reproduces false<true
                // ordering exactly — clip(bool, lo, hi) = Min(Max(v, lo), hi) with lo/hi read as
                // bytes. Fixes "clip not supported for Boolean" on the strided/transposed/F-order
                // path (the contiguous path already handled bool via its 0/1 scalar select).
                case NPTypeCode.Boolean: ClipStridedT<byte>(sBase, (byte*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Byte:    ClipStridedT<byte>(sBase, (byte*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.SByte:   ClipStridedT<sbyte>(sBase, (sbyte*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Int16:   ClipStridedT<short>(sBase, (short*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.UInt16:  ClipStridedT<ushort>(sBase, (ushort*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Char:    ClipStridedT<ushort>(sBase, (ushort*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Int32:   ClipStridedT<int>(sBase, (int*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.UInt32:  ClipStridedT<uint>(sBase, (uint*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Int64:   ClipStridedT<long>(sBase, (long*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.UInt64:  ClipStridedT<ulong>(sBase, (ulong*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Single:  ClipStridedT<float>(sBase, (float*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &DirectILKernelGenerator.FloatMaxNaN, &DirectILKernelGenerator.FloatMinNaN); break;
                case NPTypeCode.Double:  ClipStridedT<double>(sBase, (double*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &DirectILKernelGenerator.DoubleMaxNaN, &DirectILKernelGenerator.DoubleMinNaN); break;
                case NPTypeCode.Decimal: ClipStridedT<decimal>(sBase, (decimal*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &Math.Max, &Math.Min); break;
                case NPTypeCode.Half:    ClipStridedT<Half>(sBase, (Half*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &DirectILKernelGenerator.HalfMaxNaN, &DirectILKernelGenerator.HalfMinNaN); break;
                case NPTypeCode.Complex: ClipStridedT<System.Numerics.Complex>(sBase, (System.Numerics.Complex*)dst.Address, loBase, hiBase, dims, srcStr, loStr, hiStr, ndim, srcC, arr, loC, hiC, n, needLo, needHi, &DirectILKernelGenerator.ComplexMaxNaN, &DirectILKernelGenerator.ComplexMinNaN); break;
                default: throw new NotSupportedException($"clip not supported for {outType}");
            }
        }

        // One strided clip loop, shared across dtypes via Max/Min function pointers (no per-element
        // boxing or virtual dispatch). dst is C-contiguous; src and array bounds are read at
        // FlatStrideOffset(i) so any stride layout — incl. broadcast stride=0 — is honoured.
        private static unsafe void ClipStridedT<T>(
            byte* sBase, T* dst, byte* loBase, byte* hiBase,
            long[] dims, long[] srcStr, long[] loStr, long[] hiStr, int ndim,
            bool srcC, bool arr, bool loC, bool hiC,
            long n, bool needLo, bool needHi,
            delegate*<T, T, T> max, delegate*<T, T, T> min) where T : unmanaged
        {
            var s = (T*)sBase;
            var loA = (T*)loBase;
            var hiA = (T*)hiBase;
            T loScalar = (needLo && !arr && loBase != null) ? *loA : default;
            T hiScalar = (needHi && !arr && hiBase != null) ? *hiA : default;

            for (long i = 0; i < n; i++)
            {
                T v = s[srcC ? i : FlatStrideOffset(i, dims, srcStr, ndim)];
                if (needLo && loBase != null)
                {
                    T lo = arr ? loA[loC ? i : FlatStrideOffset(i, dims, loStr, ndim)] : loScalar;
                    v = max(v, lo);
                }
                if (needHi && hiBase != null)
                {
                    T hi = arr ? hiA[hiC ? i : FlatStrideOffset(i, dims, hiStr, ndim)] : hiScalar;
                    v = min(v, hi);
                }
                dst[i] = v;
            }
        }

        // ---- Policy helpers ---------------------------------------------------

        /// <summary>
        /// NEP-50 promotion of the running loop dtype with one bound. A 0-d bound is a scalar and is
        /// promoted through the array-scalar table every binary ufunc uses (<see cref="np._FindCommonArrayScalarType(NPTypeCode, NPTypeCode)"/>),
        /// so np.clip agrees with np.minimum / np.maximum, the ufuncs NumPy's <c>_clip</c> routes one-sided
        /// clips to. A C# integer literal therefore adopts the array's dtype the way a Python int does
        /// (clip(float32, 1, 3) stays float32), and a higher-kind scalar promotes (a float bound on an int array → float64).
        /// An array bound promotes strongly via <see cref="np.result_type(NPTypeCode, NPTypeCode)"/>.
        /// </summary>
        /// <param name="outType">The dtype promoted so far (the array's, then after the first bound).</param>
        /// <param name="bound">The bound to fold in, or null for none.</param>
        /// <returns>The promoted dtype; <paramref name="outType"/> itself when <paramref name="bound"/> is null.</returns>
        /// <remarks>
        /// The scalar branch used the kind-index rule of <c>np._FindCommonType(NPTypeCode[], NPTypeCode[])</c>.
        /// That rule disagreed with the table on one family: a Char array (kind 'S' in the legacy kind list, ranked
        /// above every number) kept the char dtype for a float or complex scalar, and astype then TRUNCATED the
        /// bound. clip(char, 0.5, 100.5) clipped to [0, 100] as char, where NumPy's uint16 proxy computes in float64.
        /// The two rules agree on every other dtype pair.
        /// </remarks>
        private static NPTypeCode PromoteClipBound(NPTypeCode outType, NDArray bound)
        {
            if (bound is null) return outType;
            if (bound.ndim == 0)
                return np._FindCommonArrayScalarType(outType, bound.typecode);
            return np.result_type(outType, bound.typecode);
        }

        /// <summary>
        /// The first block of NumPy's <c>numpy/_core/_methods.py::_clip</c>:
        /// <code>
        /// if a.dtype.kind in "iu":
        ///     if type(min) is int and min &lt;= np.iinfo(a.dtype).min: min = None
        ///     if type(max) is int and max &gt;= np.iinfo(a.dtype).max: max = None
        /// </code>
        /// A Python-int bound at or past the input dtype's limit cannot change any element, so it is dropped
        /// before the ufunc would have to pack it into the dtype. A bound exactly AT the limit is dropped too,
        /// which is harmless, since clipping to the limit is the identity.
        /// </summary>
        /// <param name="inputType">The dtype of the array being clipped. Its range decides, not the <c>dtype=</c> loop's.</param>
        /// <param name="min">The lower bound; set to null when it is a Python int ≤ the dtype's minimum.</param>
        /// <param name="max">The upper bound; set to null when it is a Python int ≥ the dtype's maximum.</param>
        /// <remarks>
        /// Only integer arrays take this block (NumPy's 'iu' kinds; Char rides uint16 as its NumPy proxy). On a bool,
        /// float, complex or decimal array the bounds go to the ufunc unchanged. Only Python ints are dropped
        /// (<see cref="TryGetPyInt"/>): a bool bound (<c>type(True) is int</c> is false in Python) or a float bound
        /// is kept, and an array bound always is.
        /// </remarks>
        private static void DropUnclippingPyIntBounds(NPTypeCode inputType, ref NDArray min, ref NDArray max)
        {
            if (!NDExprTypeRules.IsIntegerKind(inputType))
                return;

            (long lo, ulong hi) = NDExprTypeRules.IntBounds(inputType);
            if (TryGetPyInt(min, out Int128 vmin) && vmin <= lo)
                min = null;
            if (TryGetPyInt(max, out Int128 vmax) && vmax >= hi)
                max = null;
        }

        /// <summary>
        /// Reads a bound as NumPy's Python int, when it is one. np.clip takes NDArray bounds, so a C# integer literal
        /// (<c>np.clip(a, -1, 100)</c>) arrives as a 0-d array of the literal's dtype. Every 0-d bound of an integer
        /// dtype (the eight C# integer primitives, and char) stands for a Python int. That matches the bound's
        /// promotion: the array-scalar table makes such a bound adopt the array's dtype, the way a weak Python int
        /// does, so its value must be checked the way a Python int's is.
        /// </summary>
        /// <param name="bound">The bound to read, or null.</param>
        /// <param name="value">The bound's value when this returns true. 128 bits hold every int64 and uint64 value.</param>
        /// <returns>True for a 0-d integer-dtype bound; false for null, an array bound, or a bool/float/complex/decimal scalar.</returns>
        /// <remarks>
        /// A strong 0-d NDArray (NumPy's np.int64(5) or np.array(5)) cannot be told apart from a literal at this boundary,
        /// so it is treated the same. NumPy would promote with it instead: clip(int8, np.int64(-1000), np.int64(1000))
        /// is int64 there and an unchanged int8 here. The values agree, only the dtype differs, and the old behaviour
        /// returned wrapped garbage for the same call.
        /// </remarks>
        private static bool TryGetPyInt(NDArray bound, out Int128 value)
        {
            value = default;
            if (bound is null || bound.ndim != 0 || !NDExprTypeRules.IsIntegerKind(bound.GetTypeCode))
                return false;

            // GetAtIndex honours a 0-d VIEW's offset (a bound taken as arr[3] still reads arr[3]).
            object v = bound.GetAtIndex(0);
            value = v switch
            {
                ulong u => (Int128)u,          // past long.MaxValue: only uint64 holds it
                char c => (Int128)c,           // Convert.ToInt64(char) would throw InvalidCastException
                _ => (Int128)Convert.ToInt64(v),
            };
            return true;
        }

        /// <summary>
        /// NEP 50's packing of a kept Python-int bound into the loop dtype: NumPy raises OverflowError where the old
        /// <c>astype</c> wrapped (1000 into int8 became -24). Scalars of any other kind, and array bounds, are cast
        /// as before.
        /// </summary>
        /// <param name="bound">A bound that survived <see cref="DropUnclippingPyIntBounds"/>, or null.</param>
        /// <param name="loop">The resolved loop dtype (<c>dtype=</c> or the promoted dtype).</param>
        /// <exception cref="OverflowException">The Python int does not fit an integer <paramref name="loop"/> — see
        /// <see cref="NDExprTypeRules.CheckPyIntPacksIntoLoop"/> for the texts.</exception>
        private static void CheckPyIntBoundPacks(NDArray bound, NPTypeCode loop)
        {
            if (TryGetPyInt(bound, out Int128 value))
                NDExprTypeRules.CheckPyIntPacksIntoLoop(value, loop);
        }

        /// <summary>
        /// NumPy's <c>validate_casting</c> for an explicit <c>dtype=</c> loop: each input must reach the loop by a
        /// same_kind cast, checked in operand order, and the first failure is reported. In the routed ufunc's numbering
        /// <paramref name="lhs"/> is input 0 and each remaining bound is the next input (minimum/maximum have only
        /// input 1; clip has 1 and 2).
        /// </summary>
        /// <param name="lhs">The array being clipped (input 0), always a strong operand.</param>
        /// <param name="min">The kept lower bound, or null.</param>
        /// <param name="max">The kept upper bound, or null.</param>
        /// <param name="loop">The requested loop dtype.</param>
        /// <param name="ufunc">The routed ufunc's name, as NumPy's message quotes it.</param>
        /// <exception cref="ArgumentException">An input cannot reach <paramref name="loop"/>:
        /// "Cannot cast ufunc 'clip' input 1 from dtype('float64') to dtype('int8') with casting rule 'same_kind'".</exception>
        /// <remarks>
        /// A 0-d bound is a weak Python scalar and is checked as NEP 50's abstract DType, named by its default
        /// descriptor. A Python int reaches every integer and inexact loop but not bool (named int64). A Python
        /// float reaches only inexact loops (named float64). A Python complex reaches only complex (named complex128).
        /// So clip(uint8, 5, 10, dtype=uint8) is legal even though int64→uint8 is not same_kind, while
        /// clip(bool, 0, 2, dtype=bool) reports "input 1 from dtype('int64')". A 0-d bool, float16, decimal, and every
        /// array bound are strong and use the plain same_kind table.
        /// </remarks>
        private static void ValidateClipInputCasts(NDArray lhs, NDArray min, NDArray max, NPTypeCode loop, string ufunc)
        {
            ValidateClipInputCast(lhs.GetTypeCode, strongOnly: true, isScalar: false, 0, loop, ufunc);
            int next = 1;
            if (min is not null)
                ValidateClipInputCast(min.GetTypeCode, strongOnly: false, min.ndim == 0, next++, loop, ufunc);
            if (max is not null)
                ValidateClipInputCast(max.GetTypeCode, strongOnly: false, max.ndim == 0, next, loop, ufunc);
        }

        /// <summary>One operand of <see cref="ValidateClipInputCasts"/>; see there for the rules.</summary>
        /// <param name="from">The operand's dtype.</param>
        /// <param name="strongOnly">True for the clipped array itself, which is never a weak scalar.</param>
        /// <param name="isScalar">True when the operand is a 0-d bound (a weak Python scalar for int/float/complex dtypes).</param>
        /// <param name="index">The operand's input index in the routed ufunc.</param>
        /// <param name="loop">The requested loop dtype.</param>
        /// <param name="ufunc">The routed ufunc's name.</param>
        /// <exception cref="ArgumentException">The operand cannot reach <paramref name="loop"/> (NumPy's UFuncTypeError text).</exception>
        private static void ValidateClipInputCast(NPTypeCode from, bool strongOnly, bool isScalar, int index, NPTypeCode loop, string ufunc)
        {
            bool ok;
            string fromName;
            bool loopInexact = NDExprTypeRules.IsFloatKind(loop) || loop == NPTypeCode.Complex || loop == NPTypeCode.Decimal;
            if (!strongOnly && isScalar && NDExprTypeRules.IsIntegerKind(from))
            {
                ok = loop != NPTypeCode.Boolean;                 // a Python int never adapts to bool
                fromName = "int64";
            }
            else if (!strongOnly && isScalar && (from == NPTypeCode.Single || from == NPTypeCode.Double))
            {
                ok = loopInexact;                                // a Python float adapts to inexact loops only
                fromName = "float64";
            }
            else if (!strongOnly && isScalar && from == NPTypeCode.Complex)
            {
                ok = loop == NPTypeCode.Complex;                 // a Python complex adapts to complex only
                fromName = "complex128";
            }
            else
            {
                ok = from == loop || NDIterCasting.CanCast(from, loop, NPY_CASTING.NPY_SAME_KIND_CASTING);
                fromName = from.AsNumpyDtypeName();
            }

            if (!ok)
                throw new ArgumentException(
                    $"Cannot cast ufunc '{ufunc}' input {index} from dtype('{fromName}') to " +
                    $"dtype('{loop.AsNumpyDtypeName()}') with casting rule 'same_kind'");
        }

        private static bool IsSameKind(NPTypeCode a, NPTypeCode b)
        {
            int ga = a.GetGroup();
            int gb = b.GetGroup();
            // 0=Byte/Char, 1=signed int, 2=unsigned int  →  all "integer kind".
            bool aInt = ga >= 0 && ga <= 2;
            bool bInt = gb >= 0 && gb <= 2;
            if (aInt && bInt) return true;
            return ga == gb;
        }

        // Returns `bound` ready for the array-bounds kernel: matches lhs shape,
        // dtype outType, contiguous, offset zero. Returns the original instance
        // when those already hold (skips the otherwise-mandatory clone done by
        // `astype` on a same-dtype input).
        private static NDArray PrepareBound(NDArray bound, Shape targetShape, NPTypeCode outType)
        {
            if (bound is null) return null;
            if (bound.GetTypeCode == outType
                && bound.Shape.Equals(targetShape)
                && bound.Shape.IsContiguous
                && bound.Shape.Offset == 0)
            {
                return bound;
            }
            // Broadcast to the target shape and convert dtype. The result may stay
            // non-C-contiguous (broadcast stride=0 / F-order / strided) — that's fine:
            // ClipStrided reads the bound through its own strides at FlatStrideOffset(i),
            // pairing it correctly with the C-order result without a normalizing copy.
            return np.broadcast_to(bound, targetShape).astype(outType);
        }

        // True when a scalar (0-d) bound is already a value of outType at buffer offset 0,
        // so RunClipKernel can read it straight through .Address with no astype clone. A 0-d
        // VIEW with a non-zero offset (e.g. arr[i] used as a bound) still needs astype to
        // materialize the value at offset 0 — .Address ignores the offset.
        private static bool ScalarBoundReady(NDArray bound, NPTypeCode outType)
            => bound.GetTypeCode == outType && bound.Shape.offset == 0;

        // Returns true when `bound` is a 0-d scalar NDArray whose value is NaN.
        // Used to short-circuit float NaN-in-bounds → all-NaN result (NumPy).
        private static bool ScalarIsNaN(NDArray bound)
        {
            if (bound is null || bound.ndim != 0) return false;
            switch (bound.GetTypeCode)
            {
                case NPTypeCode.Double: return double.IsNaN(bound.GetDouble(0));
                case NPTypeCode.Single: return float.IsNaN(bound.GetSingle(0));
                case NPTypeCode.Half:   return Half.IsNaN(bound.GetHalf(0));
                default: return false;
            }
        }
    }
