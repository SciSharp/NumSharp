using System;
using System.IO;
using System.IO.Compression;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Text;
using System.Threading;

// =============================================================================
// PyUnicodeNames.cs — CPython 3.12's Unicode character names as its namereplace error handler writes them (strings phase
// 2, P2.6 milestone 4)
// =============================================================================
//
// WHAT CPYTHON DOES. PyCodec_NameReplaceErrors (Python/codecs.c) writes an unencodable character as \N{NAME} with the name
// unicodedata's C API gives (getname(code, buffer, 256, with_alias_and_seq=1) = _getucname in Modules/unicodedata.c):
//   * a code point past U+10FFFF has none;
//   * a Hangul syllable (U+AC00 .. U+D7A3) is computed: "HANGUL SYLLABLE " + the romanized initial, medial and final jamo;
//   * a CJK unified ideograph of the nine is_unified_ideograph ranges is computed: "CJK UNIFIED IDEOGRAPH-%X";
//   * every other name is read from the phrasebook — including the Private Use Area plane-15 code points U+F0000 ..
//     where CPython stores its name ALIASES and NAMED SEQUENCES, which with_alias_and_seq=1 returns for those PUA
//     characters themselves (namereplace of U+F0000 is \N{NULL}, of U+F0001 \N{NUL}).
//   An unnamed character is written as \xNN / \uNNNN / \UNNNNNNNN instead (the caller's job).
//
// THE DATA (PyUnicodeNames.Data.cs, generated by tools/gen_unicode_names.py from the oracle's CPython 3.12.12, Unicode
// 15.0.0 — never .NET, which has no character-name API): the 35,757 stored names as one zlib-deflated blob (169 KB,
// base64 in a UTF-8 literal), inflated once, at the first name a call needs (about 5 ms; namereplace is rare, so no call
// that does not use it pays for the table). The inflated records are indexed by two arrays (code point, name offset) and
// found by binary search.
//
// THE PIN. ComputeNamesHash recomputes the generator's SHA-256 over every code point's answer from these lookups, so a
// table that decodes differently from what CPython wrote fails its test.
// =============================================================================

namespace NumSharp.Backends.Strings
{
    /// <summary>
    ///     CPython 3.12's character names for the <c>namereplace</c> error handler (<c>_getucname</c> with aliases and named
    ///     sequences; see the file header).
    /// </summary>
    internal static partial class PyUnicodeNames
    {
        /// <summary>The first Hangul syllable (CPython's <c>SBase</c>).</summary>
        private const int SBase = 0xAC00;

        /// <summary>The number of Hangul syllables (<c>SCount = LCount * VCount * TCount</c> = 19 * 21 * 28).</summary>
        private const int SCount = 19 * 21 * 28;

        /// <summary>The number of syllables per initial jamo (<c>NCount = VCount * TCount</c>).</summary>
        private const int NCount = 21 * 28;

        /// <summary>The number of final jamo, the empty one included (<c>TCount</c>).</summary>
        private const int TCount = 28;

        /// <summary>CPython's <c>hangul_syllables</c>, the initial jamo column (19 entries; <c>""</c> for IEUNG).</summary>
        private static readonly string[] HangulInitial =
            { "G", "GG", "N", "D", "DD", "R", "M", "B", "BB", "S", "SS", "", "J", "JJ", "C", "K", "T", "P", "H" };

        /// <summary>CPython's <c>hangul_syllables</c>, the medial jamo column (21 entries).</summary>
        private static readonly string[] HangulMedial =
            { "A", "AE", "YA", "YAE", "EO", "E", "YEO", "YE", "O", "WA", "WAE", "OE", "YO", "U", "WEO", "WE", "WI", "YU", "EU", "YI", "I" };

        /// <summary>CPython's <c>hangul_syllables</c>, the final jamo column (28 entries; <c>""</c> for none).</summary>
        private static readonly string[] HangulFinal =
        {
            "", "G", "GG", "GS", "N", "NJ", "NH", "D", "L", "LG", "LM", "LB", "LS", "LT", "LP", "LH", "M", "B", "BS", "S", "SS",
            "NG", "J", "C", "K", "T", "P", "H",
        };

        /// <summary>CPython 3.12's <c>is_unified_ideograph</c> ranges (inclusive bounds; Unicode 15.0.0's CJK blocks).</summary>
        private static readonly (uint First, uint Last)[] UnifiedIdeographs =
        {
            (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0x20000, 0x2A6DF), (0x2A700, 0x2B739), (0x2B740, 0x2B81D),
            (0x2B820, 0x2CEA1), (0x2CEB0, 0x2EBE0), (0x30000, 0x3134A), (0x31350, 0x323AF),
        };

        /// <summary>The inflated stored names, published once (null before the first lookup that needs one).</summary>
        private static Table _table;

        /// <summary>The inflated stored names and their index (immutable once built).</summary>
        private sealed class Table
        {
            /// <summary>The inflated blob (the records: varint distance, length byte, ASCII name).</summary>
            internal readonly byte[] Blob;

            /// <summary>The stored code points, ascending.</summary>
            internal readonly int[] CodePoints;

            /// <summary>Each stored name's offset in <see cref="Blob"/> (its length byte is the byte before it).</summary>
            internal readonly int[] Offsets;

            /// <summary>Indexes an inflated blob.</summary>
            /// <param name="blob">The blob.</param>
            /// <param name="codePoints">The stored code points.</param>
            /// <param name="offsets">The name offsets.</param>
            internal Table(byte[] blob, int[] codePoints, int[] offsets)
            {
                Blob = blob;
                CodePoints = codePoints;
                Offsets = offsets;
            }
        }

        /// <summary>
        ///     The name <c>namereplace</c> writes for a code point (CPython's <c>getname(code, buffer, 256, 1)</c>), its ASCII
        ///     bytes written to <paramref name="dest"/>.
        /// </summary>
        /// <param name="cp">The code point (any 32-bit unit; past U+10FFFF has no name).</param>
        /// <param name="dest">The destination, at least <see cref="LongestName"/> bytes.</param>
        /// <returns>The name's length, or 0 when the code point has no name.</returns>
        /// <exception cref="InvalidDataException">The embedded table is corrupt (a build defect; the pin test catches it).</exception>
        internal static int GetName(uint cp, Span<byte> dest)
        {
            if (cp >= 0x110000)
                return 0;
            if (cp - SBase < SCount)
            {
                // Hangul syllable: "HANGUL SYLLABLE " + initial + medial + final (CPython's index arithmetic).
                int s = (int)cp - SBase;
                int n = Write(dest, 0, "HANGUL SYLLABLE ");
                n = Write(dest, n, HangulInitial[s / NCount]);
                n = Write(dest, n, HangulMedial[s % NCount / TCount]);
                return Write(dest, n, HangulFinal[s % TCount]);
            }
            foreach (var (first, last) in UnifiedIdeographs)
            {
                if (cp >= first && cp <= last)
                {
                    // "CJK UNIFIED IDEOGRAPH-%X": uppercase hex without leading zeros (4 or 5 digits in these ranges).
                    int n = Write(dest, 0, "CJK UNIFIED IDEOGRAPH-");
                    return Write(dest, n, cp.ToString("X", System.Globalization.CultureInfo.InvariantCulture));
                }
            }
            var table = Volatile.Read(ref _table) ?? Load();
            // A small direct-mapped cache in front of the binary search: real text repeats its characters, and namereplace
            // asks for the same few names again and again (a 64-bit entry is read and written atomically).
            ref long slot = ref Cache[cp & (CacheSize - 1)];
            long entry = Volatile.Read(ref slot);
            int offset, length;
            if (entry != 0 && (uint)(entry >> 32) == (cp | CacheValid))
            {
                offset = (int)(entry >> 8) & 0xFFFFFF;
                length = (int)(entry & 0xFF);
            }
            else
            {
                int k = Array.BinarySearch(table.CodePoints, (int)cp);
                if (k < 0)
                {
                    offset = length = 0;
                }
                else
                {
                    offset = table.Offsets[k];
                    length = table.Blob[offset - 1];
                }
                Volatile.Write(ref slot, (long)(cp | CacheValid) << 32 | (long)offset << 8 | (uint)length);
            }
            if (length == 0)
                return 0;
            table.Blob.AsSpan(offset, length).CopyTo(dest);
            return length;
        }

        /// <summary>
        ///     The length of the name <see cref="GetName"/> writes for a code point, without writing it — memoized for the BMP
        ///     (one byte per code point, filled as asked), so sizing a <c>namereplace</c> result costs one load per character
        ///     after the first time a character is met.
        /// </summary>
        /// <param name="cp">The code point.</param>
        /// <returns>The name's length, or 0 when the code point has no name.</returns>
        /// <exception cref="InvalidDataException">The embedded table is corrupt (a build defect; the pin test catches it).</exception>
        internal static int GetNameLength(uint cp)
        {
            if (cp < 0x10000)
            {
                // A byte is read and written atomically: a racing thread computes and stores the same value.
                int memo = NameLengths[cp];
                if (memo != 0)
                    return memo - 1;
            }
            Span<byte> name = stackalloc byte[256];
            int length = GetName(cp, name);
            if (cp < 0x10000)
                NameLengths[cp] = (byte)(length + 1);
            return length;
        }

        /// <summary>The BMP name lengths <see cref="GetNameLength"/> has computed: 0 unknown, else the length + 1 (the longest
        ///     name, <see cref="LongestName"/>, fits a byte). Pinned (the pinned object heap: it never moves), with 4 bytes past
        ///     U+FFFF's entry, so a 32-bit gather at any BMP code point stays inside it (<see cref="NameLengthsPointer"/>).</summary>
        private static readonly byte[] NameLengths = GC.AllocateArray<byte>(0x10000 + 4, pinned: true);

        /// <summary>
        ///     The address of <see cref="NameLengths"/> for vector code: a 32-bit load (or <c>vpgatherdd</c>) at
        ///     <c>pointer + cp</c> for any BMP code point reads the memo byte of <c>cp</c> in its low byte and never passes the
        ///     array. Valid for the process's lifetime (the array is pinned and never replaced).
        /// </summary>
        /// <remarks>Another thread may fill a byte while it is read: each byte is either 0 (unknown: ask
        ///     <see cref="GetNameLength"/>) or its final value, so a word read across a concurrent fill is still usable.</remarks>
        internal static unsafe byte* NameLengthsPointer => (byte*)Unsafe.AsPointer(ref MemoryMarshal.GetArrayDataReference(NameLengths));

        /// <summary>
        ///     Forgets every memoized name length (tests only): a <c>namereplace</c> call then sizes its elements through the
        ///     scalar rule, which fills the memo again, as the first call of a process does.
        /// </summary>
        /// <remarks>Safe while another call reads the memo: a cleared byte reads as unknown (0), and its reader computes the
        ///     length again.</remarks>
        internal static void ClearNameLengthsForTests() => Array.Clear(NameLengths);

        /// <summary>The number of cache entries (a power of two: a code point's low bits pick its entry).</summary>
        private const int CacheSize = 1024;

        /// <summary>The bit an entry's code-point half carries (code points end at bit 20), so a zero entry is never a hit.</summary>
        private const uint CacheValid = 1u << 31;

        /// <summary>
        ///     The name cache: per entry the code point with <see cref="CacheValid"/> (high 32 bits), the name's blob offset
        ///     (bits 8-31) and length (bits 0-7; 0 for a code point without a stored name). Shared by every thread: an entry is
        ///     one 64-bit value, so a reader sees an old or a new entry, never a torn one.
        /// </summary>
        private static readonly long[] Cache = new long[CacheSize];

        /// <summary>Writes an ASCII string's characters as bytes.</summary>
        /// <param name="dest">The destination.</param>
        /// <param name="at">Where to start.</param>
        /// <param name="s">The ASCII text.</param>
        /// <returns>The position after it.</returns>
        private static int Write(Span<byte> dest, int at, string s)
        {
            for (int i = 0; i < s.Length; i++)
                dest[at + i] = (byte)s[i];
            return at + s.Length;
        }

        /// <summary>
        ///     Inflates and indexes the stored names (once: concurrent first callers may each build the same immutable table;
        ///     the first publication wins and the others are dropped).
        /// </summary>
        /// <returns>The table.</returns>
        /// <exception cref="InvalidDataException">The embedded data does not inflate to the generator's blob.</exception>
        private static Table Load()
        {
            // The base64 lines carry newlines (the raw literal's line breaks, LF or CRLF by checkout): FromBase64String skips
            // white space.
            byte[] packed = Convert.FromBase64String(Encoding.ASCII.GetString(CompressedNames));
            var blob = new byte[BlobSize];
            using (var inflate = new ZLibStream(new MemoryStream(packed), CompressionMode.Decompress))
            {
                int read = 0;
                while (read < blob.Length)
                {
                    int got = inflate.Read(blob, read, blob.Length - read);
                    if (got <= 0)
                        throw new InvalidDataException("PyUnicodeNames: the embedded names inflate to fewer bytes than recorded.");
                    read += got;
                }
                if (inflate.ReadByte() >= 0)
                    throw new InvalidDataException("PyUnicodeNames: the embedded names inflate to more bytes than recorded.");
            }
            var codePoints = new int[StoredCount];
            var offsets = new int[StoredCount];
            int pos = 0, cp = -1;
            for (int i = 0; i < StoredCount; i++)
            {
                // The distance from the previous code point, an unsigned LEB128 varint (7 bits per byte, high bit = more).
                int distance = 0, shift = 0;
                byte b;
                do
                {
                    b = blob[pos++];
                    distance |= (b & 0x7F) << shift;
                    shift += 7;
                } while ((b & 0x80) != 0);
                cp += distance;
                int length = blob[pos++];
                codePoints[i] = cp;
                offsets[i] = pos;
                pos += length;
            }
            if (pos != blob.Length)
                throw new InvalidDataException("PyUnicodeNames: the embedded records do not end where the blob ends.");
            var table = new Table(blob, codePoints, offsets);
            return Interlocked.CompareExchange(ref _table, table, null) ?? table;
        }

        /// <summary>
        ///     The SHA-256 the generator recorded (<see cref="NamesHash"/>), recomputed from the runtime lookups: per code point
        ///     0 .. 0x10FFFF the name's ASCII bytes then <c>'\n'</c>, or <c>'\n'</c> alone for an unnamed one.
        /// </summary>
        /// <returns>The lowercase hex digest.</returns>
        /// <remarks>For the pin test; walks 1,114,112 code points.</remarks>
        internal static string ComputeNamesHash()
        {
            using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
            var buffer = new byte[1 << 16];
            int fill = 0;
            Span<byte> name = stackalloc byte[256];
            for (uint cp = 0; cp < 0x110000; cp++)
            {
                if (fill > buffer.Length - 300)
                {
                    sha.AppendData(buffer, 0, fill);
                    fill = 0;
                }
                int n = GetName(cp, name);
                name.Slice(0, n).CopyTo(buffer.AsSpan(fill));
                fill += n;
                buffer[fill++] = (byte)'\n';
            }
            sha.AppendData(buffer, 0, fill);
            return Convert.ToHexString(sha.GetHashAndReset()).ToLowerInvariant();
        }
    }
}
