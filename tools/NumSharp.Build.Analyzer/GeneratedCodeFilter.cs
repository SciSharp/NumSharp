using System;
using System.Collections.Concurrent;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace NumSharp.Build.Analyzer
{
    /// <summary>
    ///     The analyzers' own copy of the test Roslyn's analyzer driver applies to every diagnostic of an analyzer that
    ///     does not opt into generated code: is the diagnostic's LOCATION in generated code? The three analyzers register
    ///     with <see cref="Microsoft.CodeAnalysis.Diagnostics.GeneratedCodeAnalysisFlags.ReportDiagnostics"/> (and without
    ///     <c>Analyze</c>, so the driver still never runs them on a generated symbol), which turns the driver's test off
    ///     for their diagnostics, and drop a diagnostic here instead whenever the driver would have.
    ///     <para>
    ///     <b>Why not let the driver do it.</b> For the first diagnostic reported in a syntax tree the driver scans every
    ///     token of the tree for an identifier spelled <c>GeneratedCode</c>, outside any lock, so every analyzer thread
    ///     that reports into the same tree before the first scan finishes repeats it - materializing the whole red tree
    ///     each time. Profiled on NumSharp's own source, that scan was an eighth of NDW012's time, and for a project of
    ///     few large files with many reports it was three quarters of NDW016's. The checks here read the tree's file name,
    ///     its leading comment, its <c>#line</c> map and, only when the file's text mentions <c>GeneratedCode</c>, the
    ///     attributes of the declarations around the location - each cached per tree or bounded by the location's depth.
    ///     </para>
    ///     <para>
    ///     <b>What "generated" means</b> (the driver's rules, in its order): the tree is generated - the
    ///     <c>generated_code</c> analyzer-config option when it parses as a boolean, else a file name like
    ///     <c>*.g.cs</c> / <c>*.g.i.cs</c> / <c>*.designer.cs</c> / <c>*.generated.cs</c> / <c>TemporaryGeneratedFile_*</c>, else a
    ///     leading comment containing <c>&lt;auto-generated</c> or <c>&lt;autogenerated</c>; or the location is hidden -
    ///     in a <c>#line hidden</c> region, or before the first <c>#line</c> directive of a tree that has such a region;
    ///     or a member-level declaration enclosing the location (a namespace, type, delegate, enum member, field,
    ///     property, indexer, event, accessor, method, operator, constructor or destructor - never a parameter or a
    ///     local function) declares a symbol that carries <c>[GeneratedCode]</c> itself or through a containing symbol
    ///     (a symbol with more than one declaration - a partial type or method - never counts by its own attributes,
    ///     and stops the climb, exactly as Roslyn's <c>GeneratedCodeUtilities</c> does). A differential test pins every
    ///     rule against the driver (<c>GeneratedCodeFilterTests</c>).
    ///     </para>
    ///     <para>
    ///     Thread-safety: every cache is a concurrent dictionary of pure per-tree answers; a race computes one answer twice.
    ///     </para>
    /// </summary>
    internal sealed class GeneratedCodeFilter
    {
        /// <summary>The leading-comment markers of a generated file (Roslyn's <c>s_autoGeneratedStrings</c>).</summary>
        private static readonly string[] AutoGeneratedMarkers = { "<autogenerated", "<auto-generated" };

        /// <summary>The compilation whose trees are tested (semantic models for the declaration walk).</summary>
        private readonly Compilation _compilation;

        /// <summary><c>System.CodeDom.Compiler.GeneratedCodeAttribute</c>, or null when the compilation cannot see it (then no symbol counts as generated by attribute, as in the driver).</summary>
        private readonly INamedTypeSymbol _generatedCodeAttribute;

        /// <summary>Per tree: is the whole tree generated (option, file name, leading comment)?</summary>
        private readonly ConcurrentDictionary<SyntaxTree, bool> _generatedTrees = new ConcurrentDictionary<SyntaxTree, bool>();

        /// <summary>Per tree: can it declare a <c>[GeneratedCode]</c> symbol at all (its text mentions the attribute's name)?</summary>
        private readonly ConcurrentDictionary<SyntaxTree, bool> _mentionsGeneratedCode = new ConcurrentDictionary<SyntaxTree, bool>();

        /// <summary>Creates the filter of one compilation; nothing is computed until the first location is tested.</summary>
        /// <param name="compilation">The compilation.</param>
        /// <exception cref="ArgumentNullException"><paramref name="compilation"/> is null.</exception>
        public GeneratedCodeFilter(Compilation compilation)
        {
            _compilation = compilation ?? throw new ArgumentNullException(nameof(compilation));
            // The driver resolves the attribute the same way, once per compilation.
            _generatedCodeAttribute = compilation.GetTypeByMetadataName("System.CodeDom.Compiler.GeneratedCodeAttribute");
        }

        /// <summary>
        ///     Whether Roslyn's driver would suppress a diagnostic at <paramref name="location"/> for an analyzer that does
        ///     not report in generated code. The analyzers call it before every <c>ReportDiagnostic</c>.
        /// </summary>
        /// <param name="location">The diagnostic's primary location; a location outside source answers false (the driver never suppresses one).</param>
        /// <param name="options">The analyzer options of the reporting callback (its analyzer-config provider answers <c>generated_code</c>).</param>
        /// <param name="cancellationToken">The callback's cancellation token.</param>
        /// <returns>True when the diagnostic must not be reported.</returns>
        /// <exception cref="OperationCanceledException">The analysis was cancelled while a tree was being read.</exception>
        public bool IsInGeneratedCode(Location location, Microsoft.CodeAnalysis.Diagnostics.AnalyzerOptions options, CancellationToken cancellationToken)
        {
            if (location == null || !location.IsInSource)
                return false;
            var tree = location.SourceTree;
            if (tree == null)
                return false;

            if (IsGeneratedTree(tree, options, cancellationToken))
                return true;
            if (IsHiddenPosition(tree, location.SourceSpan.Start, cancellationToken))
                return true;
            if (_generatedCodeAttribute == null || !MentionsGeneratedCode(tree, cancellationToken))
                return false;
            return IsInsideGeneratedDeclaration(tree, location.SourceSpan, cancellationToken);
        }

        /// <summary>
        ///     Roslyn's <c>IsHiddenPosition</c>: in a tree with a <c>#line hidden</c> region, a position in a hidden
        ///     region, or before the tree's first <c>#line</c> directive (the code a generator emits ahead of the first
        ///     mapped line), is hidden; in a tree without one, nothing is.
        /// </summary>
        /// <param name="tree">The location's tree.</param>
        /// <param name="position">The location's start.</param>
        /// <param name="cancellationToken">Cancels reading the directives.</param>
        /// <returns>True for a hidden position.</returns>
        private static bool IsHiddenPosition(SyntaxTree tree, int position, CancellationToken cancellationToken)
        {
            if (!tree.HasHiddenRegions())
                return false;
            var visibility = tree.GetLineVisibility(position, cancellationToken);
            return visibility == LineVisibility.Hidden || visibility == LineVisibility.BeforeFirstLineDirective;
        }

        /// <summary>The driver's per-tree test: the <c>generated_code</c> option when it parses as a boolean, else the file name and the leading comment.</summary>
        /// <param name="tree">A tree of the compilation.</param>
        /// <param name="options">The callback's analyzer options (may lack a config provider: then only the file is read).</param>
        /// <param name="cancellationToken">Cancels reading the root.</param>
        /// <returns>True for a generated tree.</returns>
        private bool IsGeneratedTree(SyntaxTree tree, Microsoft.CodeAnalysis.Diagnostics.AnalyzerOptions options, CancellationToken cancellationToken)
        {
            if (_generatedTrees.TryGetValue(tree, out var known))
                return known;

            bool generated;
            var provider = options?.AnalyzerConfigOptionsProvider;
            if (provider != null && provider.GetOptions(tree).TryGetValue("generated_code", out var value) &&
                bool.TryParse(value, out var marked))
                generated = marked; // an explicit option wins in both directions, as in the driver
            else
                generated = IsGeneratedFileName(tree.FilePath) || BeginsWithAutoGeneratedComment(tree, cancellationToken);

            _generatedTrees.TryAdd(tree, generated);
            return generated;
        }

        /// <summary>Roslyn's generated-file names: <c>TemporaryGeneratedFile_*</c>, or a name with an extension whose stem ends in <c>.designer</c>, <c>.generated</c>, <c>.g</c> or <c>.g.i</c> (case-insensitive).</summary>
        /// <param name="filePath">The tree's path; null or empty answers false.</param>
        /// <returns>True for a generated file name.</returns>
        private static bool IsGeneratedFileName(string filePath)
        {
            if (string.IsNullOrEmpty(filePath))
                return false;
            string fileName = FileNameOf(filePath);
            if (fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
                return true;

            int dot = fileName.LastIndexOf('.');
            if (dot < 0 || dot == fileName.Length - 1)
                return false; // no extension (Roslyn's GetExtension answers empty for a trailing dot too)
            string stem = fileName.Substring(0, dot);
            return stem.EndsWith(".designer", StringComparison.OrdinalIgnoreCase) ||
                   stem.EndsWith(".generated", StringComparison.OrdinalIgnoreCase) ||
                   stem.EndsWith(".g", StringComparison.OrdinalIgnoreCase) ||
                   stem.EndsWith(".g.i", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        ///     The last segment of a path, split where Roslyn's <c>PathUtilities.GetFileName</c> splits on every OS: either
        ///     directory separator and the volume separator <c>:</c> (a tree's path may come from any OS).
        /// </summary>
        /// <param name="path">A non-empty path.</param>
        /// <returns>The file name with its extension.</returns>
        private static string FileNameOf(string path)
        {
            int separator = Math.Max(Math.Max(path.LastIndexOf('/'), path.LastIndexOf('\\')), path.LastIndexOf(':'));
            return separator < 0 ? path : path.Substring(separator + 1);
        }

        /// <summary>Whether a single-line or delimited comment before the first token of the file contains an auto-generated marker.</summary>
        /// <param name="tree">The tree.</param>
        /// <param name="cancellationToken">Cancels reading the root.</param>
        /// <returns>True when the file declares itself generated.</returns>
        private static bool BeginsWithAutoGeneratedComment(SyntaxTree tree, CancellationToken cancellationToken)
        {
            var root = tree.GetRoot(cancellationToken);
            if (!root.HasLeadingTrivia)
                return false;
            foreach (var trivia in root.GetLeadingTrivia())
            {
                // C#'s comment kinds for this test, as the C# driver passes them (documentation comments do not count).
                if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) && !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
                    continue;
                string text = trivia.ToString();
                foreach (var marker in AutoGeneratedMarkers)
                    if (text.IndexOf(marker, StringComparison.Ordinal) >= 0)
                        return true;
            }

            return false;
        }

        /// <summary>
        ///     The driver's bail-out, conservatively: the driver looks for [GeneratedCode] symbols only in a tree with an
        ///     identifier token whose value is <c>GeneratedCode</c> or <c>GeneratedCodeAttribute</c>. Such a token's text
        ///     contains <c>GeneratedCode</c> unless it is spelled with a Unicode escape, so a text without either is
        ///     answered false without walking a token; a text with one is answered true, and the declaration walk decides.
        /// </summary>
        /// <param name="tree">A tree in which a diagnostic is about to be reported.</param>
        /// <param name="cancellationToken">Cancels reading the text.</param>
        /// <returns>False when no symbol of the tree can carry the attribute.</returns>
        private bool MentionsGeneratedCode(SyntaxTree tree, CancellationToken cancellationToken)
        {
            if (_mentionsGeneratedCode.TryGetValue(tree, out var known))
                return known;
            string text = tree.GetText(cancellationToken).ToString();
            bool mentions = text.IndexOf("GeneratedCode", StringComparison.Ordinal) >= 0 ||
                            text.IndexOf("\\u", StringComparison.Ordinal) >= 0 ||
                            text.IndexOf("\\U", StringComparison.Ordinal) >= 0;
            _mentionsGeneratedCode.TryAdd(tree, mentions);
            return mentions;
        }

        /// <summary>
        ///     The driver's attribute test for one location: climbs from the innermost node at the span to the root and asks
        ///     the symbols each MEMBER-LEVEL declaration on the way declares whether they are generated by attribute.
        /// </summary>
        /// <param name="tree">The location's tree.</param>
        /// <param name="span">The location's span.</param>
        /// <param name="cancellationToken">Cancels binding.</param>
        /// <returns>True when an enclosing declaration declares a [GeneratedCode] symbol.</returns>
        /// <remarks>
        ///     The driver collects its generated symbols with Roslyn's declaration computer, which visits namespaces,
        ///     types, delegates, enum members and members (fields per declarator, properties, indexers, events,
        ///     accessors, methods, operators, constructors, destructors) - not parameters, type parameters, local
        ///     functions or locals - and a location counts only through a symbol of that set. So a
        ///     <c>[GeneratedCode]</c> parameter or local function does not make the code inside it generated, and the
        ///     climb here asks only the declarations the computer visits.
        /// </remarks>
        private bool IsInsideGeneratedDeclaration(SyntaxTree tree, TextSpan span, CancellationToken cancellationToken)
        {
            // The driver binds the same way (Compilation.GetSemanticModel on the location's tree); this runs only for a
            // tree whose text mentions the attribute, and only when a diagnostic is about to be reported in it.
            var model = _compilation.GetSemanticModel(tree);
            var root = tree.GetRoot(cancellationToken);
            for (var node = root.FindNode(span, findInsideTrivia: false, getInnermostNodeForTie: true); node != null; node = node.Parent)
            {
                switch (node)
                {
                    case BaseFieldDeclarationSyntax field:
                        // A field or event-field declaration declares one symbol per declarator (the driver's
                        // GetDeclaredSymbolsForNode answers them all for the declaration node).
                        foreach (var declarator in field.Declaration.Variables)
                            if (IsGeneratedByAttribute(model.GetDeclaredSymbol(declarator, cancellationToken)))
                                return true;
                        break;

                    case VariableDeclaratorSyntax declarator when declarator.Parent?.Parent is BaseFieldDeclarationSyntax:
                    case BaseNamespaceDeclarationSyntax _:
                    case BaseTypeDeclarationSyntax _:
                    case DelegateDeclarationSyntax _:
                    case EnumMemberDeclarationSyntax _:
                    case BasePropertyDeclarationSyntax _:
                    case AccessorDeclarationSyntax _:
                    case BaseMethodDeclarationSyntax _:
                        if (IsGeneratedByAttribute(model.GetDeclaredSymbol(node, cancellationToken)))
                            return true;
                        break;
                }
            }

            return false;
        }

        /// <summary>
        ///     Roslyn's <c>IsGeneratedSymbolWithGeneratedCodeAttribute</c>: a symbol with one declaration that carries
        ///     <c>[GeneratedCode]</c>, or whose containing symbol is generated by the same test. A symbol with more than one
        ///     declaration (a partial type or method) answers false and ends the climb; a namespace's own attributes are
        ///     not read.
        /// </summary>
        /// <param name="symbol">A declared symbol; null answers false.</param>
        /// <returns>True for a symbol generated by attribute.</returns>
        private bool IsGeneratedByAttribute(ISymbol symbol)
        {
            for (var s = symbol; s != null; s = s.ContainingSymbol)
            {
                if (s.Kind != SymbolKind.Namespace)
                {
                    if (s.DeclaringSyntaxReferences.Length > 1)
                        return false;
                    foreach (var attribute in s.GetAttributes())
                        if (SymbolEqualityComparer.Default.Equals(_generatedCodeAttribute, attribute.AttributeClass))
                            return true;
                }
            }

            return false;
        }
    }
}
