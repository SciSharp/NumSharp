"""Renders polyvander_results.md from a polyvander_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polyvander_numpy.py):
    python polyvander_report.py ns_vander.tsv > polyvander_results.md

The C# runner has already checked every cell's result bytes against NumPy's SHA-256 before timing it; this
script only refuses to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "D": "1-D float64 points: 1 / 16 / 1K / 100K / 1M points x degree 3 / 10 / 30 (30 up to 100K)",
    "T": "point dtypes: float32 / float16 / complex128 / int32 / int64 / uint8 / bool at 1K and 100K points, degree 5",
    "L": "layouts @ 100K points, degree 5: strided, reversed, F-order and transposed 2-D, broadcast",
    "N": "N-D points: (100, 1000) degree 5, (10, 10, 1000) degree 3",
    "V": "2-D outer products: 1 / 100 / 10K / 100K points x degrees (1,1) / (3,3) / (5,5) / (10,10)",
    "W": "3-D outer products: 1 / 100 / 10K / 100K points x degrees (1,1,1) / (2,2,2) / (3,3,3); (5,5,5) up to 10K",
    "M": "2-D mixed / other dtypes @ 10K points, degrees (3, 3): float32+int32, float16+int8, float32, complex128, "
         "a strided + reversed pair",
    "S": "small calls (the fixed per-call cost): a scalar x, 3 points; 2-D / 3-D scalar points",
    "A": "argument forms: a Python-list x (16 / 1000 points), Python-list 2-D points (100 / 1000), a tuple / an ndarray "
         "of degrees; the C#-only kinds (a typed double[] x, a List<double> x / 2-D points, a 0-d array degree); the object "
         "stack of scalars (a BigInteger past uint64 among 2-D / 3-D scalar points, one dtype and mixed dtypes)",
}


def icon(r):
    """The house NPY/NS status icon."""
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def main():
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) == 5 and p[0][:2] in {f"{s}/" for s in SECTIONS}:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] != "exact"]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells did not match NumPy's bytes, e.g. {bad[0]}")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0][0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial Vandermonde matrices (U5) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyvander_report.py` from a `polyvander_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was compared byte for")
    w("byte (SHA-256 of dtype, shape and data) against NumPy's before it was timed: all "
      f"{len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same 4 logical CPUs (`NS_PROBE_AFFINITY=0xF0`), never concurrently; C# in")
    w("Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up (warm, sleep, warm again);")
    w("best-of-rounds per side; inputs from one exact formula both languages evaluate (no arrays on disk).")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, _ in rs:
            w(f"| `{label[2:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
