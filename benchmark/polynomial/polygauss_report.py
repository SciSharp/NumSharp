"""Renders polygauss_results.md from one or more polygauss_bench.cs runs (the TSVs it prints).

Usage (from this directory, after full runs of both sides — see polygauss_numpy.py):
    python polygauss_report.py ns_gauss_1.tsv ns_gauss_2.tsv ns_gauss_3.tsv > polygauss_results.md

Each TSV is one alternating pair of runs (NumPy, then NumSharp joined with that NumPy run). The report takes every time
column's per-cell minimum over the files — the best window of each side, so a background burst during one run does not
decide a ratio. The C# runner has already checked every cell's two result slots against NumPy's SHA-256 before timing
it; this script refuses to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "L": "leggauss at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500",
    "G": "laggauss at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500",
    "H": "hermgauss at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500 / 1000 (1000: NumPy's results hold NaN)",
    "E": "hermegauss at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500 / 1000",
    "A": "argument forms at degree 20: an np.uint16 scalar (NumSharp's char); a Python bool (degree 1)",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def geomean(xs):
    """The geometric mean.

    Args:
        xs: Positive numbers (at least one).

    Returns:
        exp(mean(log(x))).
    """
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def read(paths):
    """Reads the runner TSVs and merges them cell by cell.

    Args:
        paths: The TSV files (one per run pair).

    Returns:
        An ordered dict label -> (NumSharp us, NumPy us, NumSharp eigvalsh us, NumPy eigvalsh us), each the minimum over
        the runs that measured the cell; exits with an error when any run reports a byte mismatch.
    """
    cells = collections.OrderedDict()
    for path in paths:
        for line in open(path, encoding="utf-8"):
            p = line.rstrip("\n").split("\t")
            # A cell label has a "/" (the per-section summary lines that follow the cells do not).
            if len(p) != 8 or "/" not in p[0] or p[0].split("/")[0] not in SECTIONS:
                continue
            if p[7] != "exact":
                sys.exit(f"refusing to render: {path} cell {p[0]} did not match NumPy's bytes ({p[7]})")
            t = (float(p[1]), float(p[2]), float(p[4]), float(p[5]))
            old = cells.get(p[0])
            cells[p[0]] = t if old is None else tuple(min(a, b) for a, b in zip(old, t))
    return cells


def main():
    """Reads the runner TSVs (argv[1:]) and prints the Markdown report.

    Returns:
        None.
    """
    cells = read(sys.argv[1:])
    by = collections.defaultdict(list)
    for label, t in cells.items():
        by[label.split("/")[0]].append((label, *t))
    rows = [r for s in SECTIONS for r in by.get(s, [])]
    ratio = lambda r: r[2] / r[1]
    ceiling = lambda r: r[2] / r[3]
    below = [r for r in rows if ratio(r) < 1.5]

    out = []
    w = out.append
    w("# numpy.polynomial Gauss-Legendre / -Laguerre / -Hermite quadrature (U8) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polygauss_report.py` from `polygauss_bench.cs` runs. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's two result slots were compared byte")
    w(f"for byte (SHA-256 of dtype, shape and data) against NumPy's before it was timed: all {len(rows)} cells are bit-exact")
    w("(the degree-1000 Hermite cells included, whose nodes and weights hold NaN: the NaN payloads match too).")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently, OpenBLAS at ONE")
    w("thread on both sides (NumPy under `OPENBLAS_NUM_THREADS=1`, NumSharp through `NumSharp.Interop.OpenBLAS`, the same")
    w("scipy-openblas build); C# in Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up;")
    w(f"best-of-rounds per side, and the per-cell best over {len(sys.argv) - 1} alternating NumPy / NumSharp run pairs.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("**The eigvalsh ceiling.** Every function is NumPy's statements around ONE `np.linalg.eigvalsh` call on the")
    w("companion matrix of `[0]*deg + [1]`, and both libraries run that call through the same LAPACK `syevd`. The")
    w("`eigvalsh` columns time that call alone, on that matrix; `ceiling` = NumPy's whole call over NumSharp's eigvalsh")
    w("alone — the NPY/NS a function would reach if every statement NumSharp owns took no time. NumPy's time at low degrees")
    w("is its three `{p}val` calls (Legendre, Laguerre) or its three normalised Hermite recurrences (Python loops of")
    w("deg - 1 steps, five array statements each, where NumSharp runs one IL kernel). syevd's work grows as deg^3 and takes")
    w("over both calls from degree ~100, so the ratio falls toward the ceiling, and where the ceiling itself is under 1.5x")
    w("no composition can reach 1.5x.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | geomean ceiling | Covers |")
    w("|---|---:|---:|---:|---:|---|")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"| {s} | {len(rs)} | {min(ratio(r) for r in rs):.2f} | {geomean([ratio(r) for r in rs]):.2f} | "
          f"{geomean([ceiling(r) for r in rs]):.2f} | {SECTIONS[s]} |")
    w(f"| **all** | **{len(rows)}** | **{min(ratio(r) for r in rows):.2f}** | **{geomean([ratio(r) for r in rows]):.2f}** "
      f"| **{geomean([ceiling(r) for r in rows]):.2f}** | |")
    w("")
    if below:
        w(f"**Cells under 1.5x ({len(below)}):** " + "; ".join(
            f"`{r[0]}` {ratio(r):.2f} (ceiling {ceiling(r):.2f}, eigvalsh {100 * r[3] / r[1]:.0f}% of NumSharp's call)"
            for r in sorted(below, key=ratio)) + ".")
        w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS | NumSharp eigvalsh µs | NumPy eigvalsh µs | ceiling | eigvalsh share |")
        w("|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in rs:
            label, ns, npy, nse, npe = r
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio(r))} {ratio(r):.2f} | {nse:,.3f} | "
              f"{npe:,.3f} | {ceiling(r):.2f} | {100 * nse / ns:.0f}% |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
