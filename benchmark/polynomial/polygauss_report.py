"""Renders polygauss_results.md from a polygauss_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polygauss_numpy.py):
    python polygauss_report.py ns_gauss.tsv > polygauss_results.md

The C# runner has already checked every cell's two result slots against NumPy's SHA-256 before timing it; this script
only refuses to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "L": "leggauss at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500",
    "G": "laggauss at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500",
    "A": "argument forms at degree 20: an np.uint16 scalar (NumSharp's char); a Python bool (degree 1)",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def main():
    """Reads the runner's TSV (argv[1]) and prints the Markdown report; exits with an error on any byte mismatch.

    Returns:
        None.
    """
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        # A cell label has a "/" (the per-section summary lines that follow the cells do not).
        if len(p) == 5 and "/" in p[0] and p[0].split("/")[0] in SECTIONS:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] != "exact"]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells did not match NumPy's bytes, e.g. {bad[0]}")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0].split("/")[0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial Gauss-Legendre / Gauss-Laguerre quadrature (U8) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polygauss_report.py` from a `polygauss_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's two result slots were compared byte")
    w(f"for byte (SHA-256 of dtype, shape and data) against NumPy's before it was timed: all {len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently, OpenBLAS at ONE")
    w("thread on both sides (NumPy under `OPENBLAS_NUM_THREADS=1`, NumSharp through `NumSharp.Interop.OpenBLAS`, the same")
    w("scipy-openblas build); C# in Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up;")
    w("best-of-rounds per side. NumPy's time at low degrees is its three `{p}val` calls, Python loops over the deg + 1")
    w("coefficients; from degree ~100 both sides wait on the same LAPACK `syevd`, so the ratio falls toward 1 there.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, _ in rs:
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
