"""Renders polyroots_results.md from a polyroots_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polyroots_numpy.py):
    python polyroots_report.py ns_roots.tsv > polyroots_results.md

The C# runner has already checked every cell's result against NumPy's before timing it — bytes ("exact"), or for a
roots cell that ran LAPACK geev on a host whose OpenBLAS build differs from the one NumPy loads ("close": values within
a relative 1e-12). This script refuses to render a run reporting anything else, so a committed report is always a
checked one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "C": "{p}companion, float64: 2 (linear) to 1001 coefficients; power series also 2898 (67 MB, OS-zeroed pages)",
    "T": "{p}companion in float32 / float16 / complex128 / int64: 11 / 51 / 201 coefficients",
    "R": "{p}roots, float64: a constant, a linear and 3 / 6 / 11 / 51 / 201-coefficient series",
    "S": "{p}roots in float32 / complex128 (11, 51), int64 (11) and float16 (linear)",
    "L": "layouts: companion of a stride-2 / reversed 51-coefficient series, roots of a stride-2 11-coefficient one",
    "A": "Python-list arguments: 11 floats to companion and roots",
}


def icon(r):
    """The house NPY/NS status icon."""
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def bound(label):
    """Why a cell below 1.5x is where it is — the work both sides must do that dominates its time (measured with the
    probes the U7 block of docs/plans/numpy-polynomial.md quotes)."""
    sec, _base, dt, n = label.split("/")
    n = int(n[1:])
    if sec in ("R", "S") and n >= 51:
        return "LAPACK `geev` (the same scipy-openblas call on both sides) is the call"
    if sec in ("R", "S") and dt == "complex128":
        return "`zgeev` is ~20.7 of NumSharp's ~22 µs (NumPy's eigvals alone 23.8 µs): ceiling ~1.43x"
    if sec in ("R", "S"):
        return "LAPACK `geev` dominates the call"
    if n >= 2898:
        return "a 67 MB fresh matrix: one demand-zero page fault per touched page, on both sides"
    if n >= 201:
        return "zeroing the 320 KB matrix (L2 store bandwidth): NumSharp's alloc+zero 4.1 µs vs NumPy's np.zeros 3.9 µs"
    return "fixed per-call cost"


def main():
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) == 5 and p[0][:2] in {f"{s}/" for s in SECTIONS}:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] not in ("exact", "close")]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells failed their check, e.g. {bad[0]}")
    close = sum(1 for r in rows if r[4] == "close")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0][0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial companion matrices and roots (U7) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyroots_report.py` from a `polyroots_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was checked against")
    w(f"NumPy's before it was timed: {len(rows) - close} of {len(rows)} cells are bit-exact (SHA-256 of dtype, shape")
    w("and data; a float32 series' complex roots compared as NumPy's complex64 values widened to complex128, the")
    w("values NumSharp carries)" + (f"; the other {close} (marked ≈) ran LAPACK on an OpenBLAS build other than"
                                   " NumPy's and agree to a relative 1e-12." if close else "."))
    w("Roots of degree 2 or more are `np.linalg.eigvals` of the companion matrix — LAPACK `geev` on both sides,")
    w("NumSharp through `NumSharp.Interop.OpenBLAS` (the scipy-openblas NumPy loads) at one thread: as the degree")
    w("grows, both sides converge on the same `geev` call, the physical ceiling of the larger roots cells.")
    w("")
    w("Method: both sides pinned to the same 4 logical CPUs (`NS_PROBE_AFFINITY=0xF0`), never concurrently; C# in")
    w("Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up (warm, sleep, warm again);")
    w("best-of-rounds per side (rounds sized from one timed NumPy call); inputs from one exact formula both languages")
    w("evaluate (no arrays on disk); `OPENBLAS_NUM_THREADS=1` on the NumPy side.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    slow = sorted((r for r in rows if r[3] < 1.5), key=lambda r: r[3])
    if slow:
        w("## Below 1.5× — and what bounds each")
        w("")
        w("Every cell under 1.5× spends its time in work both libraries must do the same way: LAPACK `geev` for roots of")
        w("degree 50 and up (and ~90 % of a degree-10 complex root), zeroing the companion matrix at degree 200 (a")
        w("memset over L2 on both sides), the page faults of a 67 MB fresh matrix. Cells this close to the floor move")
        w("±20 % from run to run with the host's load (the degree-200 power-series companion measured 1.27–1.63×).")
        w("")
        w("| Cell | NPY/NS | Bound |")
        w("|---|---:|---|")
        for label, ns, npy, ratio, check in slow:
            w(f"| `{label}` | {ratio:.2f} | {bound(label)} |")
        w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, check in rs:
            mark = " ≈" if check == "close" else ""
            w(f"| `{label[2:]}`{mark} | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
