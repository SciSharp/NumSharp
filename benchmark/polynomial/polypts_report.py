"""Renders polypts_results.md from a polypts_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polypts_numpy.py):
    python polypts_report.py ns_pts.tsv > polypts_results.md

The C# runner has already checked every cell's result bytes against NumPy's SHA-256 before timing it; this script only
refuses to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "P1": "chebpts1 at 1 / 2 / 5 / 16 / 100 / 1K / 10K / 100K / 1M points",
    "P2": "chebpts2 at 2 / 5 / 16 / 100 / 1K / 10K / 100K / 1M points",
    "G": "chebgauss at 1 / 5 / 16 / 100 / 1K / 10K / 100K / 1M nodes (both slots)",
    "A": "argument forms at 1K: a Python float, a 0-d int64 array, an np.uint16 scalar (NumSharp's char), a Python bool",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def main():
    """Reads the runner's TSV (argv[1]) and prints the Markdown report; exits with an error on any byte mismatch.

    Returns:
        None.
    """
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        # A cell label has a "/" (the per-section summary lines that follow the cells do not).
        if len(p) == 5 and "/" in p[0] and p[0].split("/")[0] in SECTIONS:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] != "exact"]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells did not match NumPy's bytes, e.g. {bad[0]}")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0].split("/")[0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial Chebyshev points and Gauss-Chebyshev quadrature (U8) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polypts_report.py` from a `polypts_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was compared byte for")
    w("byte (SHA-256 of dtype, shape and data; both slots of chebgauss) against NumPy's before it was timed: all "
      f"{len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently; C# in Release")
    w("with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up (warm, sleep, warm again); best-of-rounds")
    w("per side. Every node is the C runtime's sin / cos on both sides (about 4.5 ns), so the large counts measure what")
    w("NumPy spends around it: its int64 ramp, its intermediate arrays and its Python statements.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    w("chebpts1 computes half its sines: its ramp is antisymmetric and the C runtime's sin is odd bit for bit, so each")
    w("sine's negation fills the mirrored slot (the same bytes as one sin per element). chebpts2 and chebgauss have no")
    w("exact pairs, so their 10K cells sit at the cos floor: there NumPy's extra passes are cache-resident and nearly free,")
    w("and both sides spend about 5.5 ns per node in the same C runtime cos (NumSharp's managed call is ~10% slower per")
    w("element than NumPy's C loop), which caps the ratio near 1.2x.")
    w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, _ in rs:
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
