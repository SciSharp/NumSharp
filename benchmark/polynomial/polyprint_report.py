"""Renders polyprint_results.md from one or more polyprint_bench.cs runs (the TSVs it prints).

Usage (from this directory, after full runs of both sides — see polyprint_numpy.py):
    python polyprint_report.py ns_print_1.tsv ns_print_2.tsv ns_print_3.tsv > polyprint_results.md

Each TSV is one alternating pair of runs (NumPy, then NumSharp joined with that NumPy run). The report takes each side's
per-cell minimum over the files — the best window of each side, so a background burst during one run does not decide a
ratio. The C# runner has already compared every cell's text with NumPy's before timing it; this script refuses to render
a run that reports a mismatch, so a committed report is always an exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "FP": "np.format_float_positional: float64 / float32 / float16 x 7 values x 8 option sets (unique, a unique cut, "
          "exact to 17 and 60 places, fractional=False, min_digits=20, padding, trim='-')",
    "FS": "np.format_float_scientific: the widths x values x 5 option sets (unique, a unique cut, exact to 17 digits, "
          "exp_digits=5, min_digits=9)",
    "FF": "polyutils.format_float: the widths x values x the default and floatmode='fixed' print options, and non-floating "
          "x (a Python int, a 0-d array, a 1-D array: str(x))",
    "SP": "set_default_printstyle('ascii' / 'unicode')",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def geomean(xs):
    """The geometric mean.

    Args:
        xs: Positive numbers (at least one).

    Returns:
        exp(mean(log(x))).
    """
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def read(paths):
    """Reads the runner TSVs and merges them cell by cell.

    Args:
        paths: The TSV files (one per run pair).

    Returns:
        An ordered dict label -> (NumSharp us, NumPy us), each the minimum over the runs that measured the cell; exits with
        an error when any run reports a text mismatch.
    """
    cells = collections.OrderedDict()
    for path in paths:
        for line in open(path, encoding="utf-8"):
            p = line.rstrip("\n").split("\t")
            # A cell label has a "/" (the per-section summary lines that follow the cells do not).
            if len(p) != 5 or "/" not in p[0] or p[0].split("/")[0] not in SECTIONS:
                continue
            if p[4] != "exact":
                sys.exit(f"refusing to render: {path} cell {p[0]} did not match NumPy's text ({p[4]})")
            t = (float(p[1]), float(p[2]))
            old = cells.get(p[0])
            cells[p[0]] = t if old is None else tuple(min(a, b) for a, b in zip(old, t))
    return cells


def main():
    """Reads the runner TSVs (argv[1:]) and prints the Markdown report.

    Returns:
        None.
    """
    cells = read(sys.argv[1:])
    rows = [(label, ns, npy, npy / ns) for label, (ns, npy) in cells.items()]
    by = collections.defaultdict(list)
    for r in rows:
        by[r[0].split("/")[0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial printing and the scalar float formatters (U11) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyprint_report.py` from `polyprint_bench.cs` runs. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's text was compared with NumPy's")
    w(f"before it was timed: all {len(rows)} cells are exact.")
    w("")
    w(f"Method: {len(sys.argv) - 1} alternating pairs of runs (NumPy, then NumSharp), each side's best window per cell;")
    w("both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently; C# in Release with")
    w("`DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up; best-of-rounds per side. The FF cells run inside")
    w("`np.printoptions(**opts)` on both sides when they set an option (`floatmode='fixed'`), as the series classes do.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {geomean(rs):.2f} | {SECTIONS[s]} |")
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{geomean(allr):.2f}** | |")
    w("")
    w("Where the time goes. A unique request whose cutoff does not cut the shortest digits is Ryu's shortest digits (the")
    w("fast path), 0.1-0.3 us. Every other request runs NumPy's Dragon4 loop on NumPy's own in-place BigInt arithmetic,")
    w("ported with 64-bit blocks (Dragon4.BigInt.cs): no allocation, half NumPy's passes per digit, and two exact")
    w("shortcuts NumPy's loop does not take — margins dropped once they pass the scale (min_digits past the shortest")
    w("digits), and 19 digits per division where the margins no longer matter (long exact runs: 1e300 to every place).")
    w("NumPy's side adds its Python wrapper (about 0.6 us of argument checks around the C call); format_float adds")
    w("np.get_printoptions and NumPy-scalar arithmetic (3-5 us), and set_default_printstyle a tuple membership test.")
    w("")
    slow = sorted((r for r in rows if r[3] < 1.5), key=lambda r: r[3])
    if slow:
        w("Cells below 1.5x:")
        w("")
        for label, ns, npy, ratio in slow:
            w(f"- `{label}` {ratio:.2f} (NumSharp {ns:.3f} us, NumPy {npy:.3f} us)")
        w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio in rs:
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
