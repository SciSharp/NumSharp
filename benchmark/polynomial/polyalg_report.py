"""Renders polyalg_results.md from a polyalg_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polyalg_numpy.py):
    python polyalg_report.py ns_alg.tsv > polyalg_results.md

The C# runner has already checked every cell's result against NumPy's before timing it — bytes ("exact"), or for
the products NumPy computes with OpenBLAS's vector dot kernels ("close": NumSharp's default managed kernels sum in
another order, so the values agree to a relative 1e-12; byte parity for those comes with NumSharp.Interop.OpenBLAS,
gated by the host-pinned polyalgebra_parity oracle tier). This script refuses to render a run reporting anything
else, so a committed report is always a checked one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "X": "{p}mulx: float64 / float32 / float16 / complex128 series of 3 to 10000 coefficients",
    "M": "{p}mul, float64: short, medium, and (convolving bases) long products and long-signal x short-kernel",
    "T": "{p}mul in float32 / float16 / complex128 / int64: 10x10, 100x100, (convolving bases) 1000x1000",
    "D": "{p}div: float64 5/3, 20/7, 50/16, 200/50; float32 / complex128 at 50/16",
    "P": "{p}pow: (3, 2), (5, 5), (10, 8), (convolving bases) (50, 4) and complex128 / float32 (10, 4)",
    "R": "{p}fromroots: 3 / 10 / 30 / 100 float64 roots; complex128 10 / 30",
    "C": "X2poly / poly2X: 3 / 10 / 50 / 200 float64 coefficients; float32 / complex128 at 50",
    "A": "Python-list arguments: mulx 100, mul 10x10, div 20/7, pow (10, 3), fromroots 10",
}


def icon(r):
    """The house NPY/NS status icon."""
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def main():
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) == 5 and p[0][:2] in {f"{s}/" for s in SECTIONS}:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] not in ("exact", "close")]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells failed their check, e.g. {bad[0]}")
    close = sum(1 for r in rows if r[4] == "close")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0][0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial series algebra (U2) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyalg_report.py` from a `polyalg_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was checked against")
    w(f"NumPy's before it was timed: {len(rows) - close} of {len(rows)} cells are bit-exact (SHA-256 of dtype, shape")
    w(f"and data); the other {close} (marked ≈) are products NumPy computes with OpenBLAS's vector dot kernels, whose")
    w("summation order NumSharp's default managed kernels do not follow — their values agree to a relative 1e-12, and")
    w("byte parity for them comes with `NumSharp.Interop.OpenBLAS` (gated by the host-pinned `polyalgebra_parity`")
    w("oracle tier). These cells time the managed default.")
    w("")
    w("Method: both sides pinned to the same 4 logical CPUs (`NS_PROBE_AFFINITY=0xF0`), never concurrently; C# in")
    w("Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up (warm, sleep, warm again);")
    w("best-of-rounds per side (rounds sized from one timed NumPy call); inputs from one exact formula both languages")
    w("evaluate (no arrays on disk); `OPENBLAS_NUM_THREADS=1` on the NumPy side.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, check in rs:
            mark = " ≈" if check == "close" else ""
            w(f"| `{label[2:]}`{mark} | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
