"""Renders polyfit_results.md from one or more polyfit_bench.cs runs (the TSVs it prints).

Usage (from this directory, after full runs of both sides — see polyfit_numpy.py):
    python polyfit_report.py ns_fit_1.tsv ns_fit_2.tsv ns_fit_3.tsv > polyfit_results.md

Each TSV is one alternating pair of runs (NumPy, then NumSharp joined with that NumPy run). The report takes every time
column's per-cell minimum over the files — the best window of each side, so a background burst during one run does not
decide a ratio. The C# runner has already checked every cell's result against NumPy's SHA-256 before timing it; this
script refuses to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "C": "chebfit over n points x degree: n = 10 / 100 / 1,000 / 100,000, degree 3 / 10 / 30",
    "S": "the six bases at n = 20, degree 5 (lstsq costs a few microseconds: the composition's own cost)",
    "B": "the other five bases at n = 1,000, degree 10",
    "K": "kinds at n = 1,000, degree 10: weights, a 2-D y (3 data sets), full=True, a degree list, float32, complex y, "
         "an integer x (polyfit, degree 3), Python lists",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def geomean(xs):
    """The geometric mean.

    Args:
        xs: Positive numbers (at least one).

    Returns:
        exp(mean(log(x))).
    """
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def read(paths):
    """Reads the runner TSVs and merges them cell by cell.

    Args:
        paths: The TSV files (one per run pair).

    Returns:
        An ordered dict label -> (NumSharp us, NumPy us, NumSharp lstsq us, NumPy lstsq us), each the minimum over the
        runs that measured the cell; exits with an error when any run reports a byte mismatch.
    """
    cells = collections.OrderedDict()
    for path in paths:
        for line in open(path, encoding="utf-8"):
            p = line.rstrip("\n").split("\t")
            # A cell label has a "/" (the per-section summary lines that follow the cells do not).
            if len(p) != 8 or "/" not in p[0] or p[0].split("/")[0] not in SECTIONS:
                continue
            if p[7] != "exact":
                sys.exit(f"refusing to render: {path} cell {p[0]} did not match NumPy's bytes ({p[7]})")
            t = (float(p[1]), float(p[2]), float(p[4]), float(p[5]))
            old = cells.get(p[0])
            cells[p[0]] = t if old is None else tuple(min(a, b) for a, b in zip(old, t))
    return cells


def main():
    """Reads the runner TSVs (argv[1:]) and prints the Markdown report.

    Returns:
        None.
    """
    cells = read(sys.argv[1:])
    by = collections.defaultdict(list)
    for label, t in cells.items():
        by[label.split("/")[0]].append((label, *t))
    rows = [r for s in SECTIONS for r in by.get(s, [])]
    ratio = lambda r: r[2] / r[1]
    ceiling = lambda r: r[2] / r[3]
    below = [r for r in rows if ratio(r) < 1.5]

    out = []
    w = out.append
    w("# numpy.polynomial least-squares fits (U6: {p}fit) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyfit_report.py` from `polyfit_bench.cs` runs. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was compared byte for byte")
    w("(SHA-256 of dtype, shape and data of every slot, the four `full=True` statistics included) against NumPy's before it")
    w(f"was timed: all {len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently, OpenBLAS at ONE")
    w("thread on both sides (NumPy under `OPENBLAS_NUM_THREADS=1`, NumSharp through `NumSharp.Interop.OpenBLAS`, the same")
    w("scipy-openblas build); C# in Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up;")
    w(f"best-of-rounds per side, and the per-cell best over {len(sys.argv) - 1} alternating NumPy / NumSharp run pairs.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("**The lstsq ceiling.** A fit is NumPy's `_fit` statements around ONE `np.linalg.lstsq` call, and both libraries run")
    w("that call through the same LAPACK `gelsd`. The `lstsq` columns time that call alone, on the operands `_fit` hands")
    w("it; `ceiling` = NumPy's whole call over NumSharp's lstsq alone — the NPY/NS a fit would reach if every statement")
    w("NumSharp owns took no time. `lstsq share` is the part of NumSharp's call spent in lstsq. As the degree grows gelsd")
    w("takes over both calls (its work grows as n x (deg + 1)^2), so the ratio falls toward the ceiling, and where the")
    w("ceiling itself is under 1.5x no composition can reach 1.5x: the remaining gap is NumPy's own statements against")
    w("NumSharp's, which run 2-4x faster than NumPy's (the fused norm pass, the one-kernel Vandermonde matrix, the")
    w("C-ordered column scaling).")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | geomean ceiling | Covers |")
    w("|---|---:|---:|---:|---:|---|")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"| {s} | {len(rs)} | {min(ratio(r) for r in rs):.2f} | {geomean([ratio(r) for r in rs]):.2f} | "
          f"{geomean([ceiling(r) for r in rs]):.2f} | {SECTIONS[s]} |")
    w(f"| **all** | **{len(rows)}** | **{min(ratio(r) for r in rows):.2f}** | **{geomean([ratio(r) for r in rows]):.2f}** "
      f"| **{geomean([ceiling(r) for r in rows]):.2f}** | |")
    w("")
    if below:
        w(f"**Cells under 1.5x ({len(below)}):** " + "; ".join(
            f"`{r[0]}` {ratio(r):.2f} (ceiling {ceiling(r):.2f}, lstsq {100 * r[3] / r[1]:.0f}% of NumSharp's call)"
            for r in sorted(below, key=ratio)) + ".")
        w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS | NumSharp lstsq µs | NumPy lstsq µs | ceiling | lstsq share |")
        w("|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in rs:
            label, ns, npy, nsl, npl = r
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio(r))} {ratio(r):.2f} | {nsl:,.3f} | "
              f"{npl:,.3f} | {ceiling(r):.2f} | {100 * nsl / ns:.0f}% |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
