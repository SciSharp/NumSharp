"""Renders polyweight_results.md from a polyweight_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polyweight_numpy.py):
    python polyweight_report.py ns_weight.tsv > polyweight_results.md

The C# runner has already checked every cell's result bytes against NumPy's SHA-256 before timing it; this script only
refuses to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "D": "1-D float64 points: 1 / 16 / 1K / 100K / 1M",
    "T": "point dtypes: float32 / float16 / complex128 / int32 / int16 / uint8 / bool at 1K / 100K / 1M (no complex "
         "chebweight, no bool lagweight)",
    "L": "layouts @ 100K points: strided, reversed, F-order and transposed 2-D, a transposed 3-D, a row broadcast, a "
         "stride-0 broadcast",
    "S": "small calls (the fixed per-call cost): a Python float, a 0-d float64 array, 3 points",
    "A": "argument forms: a Python int, a typed double[] (an ndarray to NumPy), an np.float16 scalar",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def main():
    """Reads the runner's TSV (argv[1]) and prints the Markdown report; exits with an error on any byte mismatch."""
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) == 5 and p[0][:2] in {f"{s}/" for s in SECTIONS}:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] != "exact"]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells did not match NumPy's bytes, e.g. {bad[0]}")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0][0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial weight functions (U8) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyweight_report.py` from a `polyweight_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was compared byte for")
    w("byte (SHA-256 of dtype, shape and data) against NumPy's before it was timed: all "
      f"{len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently; C# in Release")
    w("with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up (warm, sleep, warm again); best-of-rounds")
    w("per side; inputs from one exact formula both languages evaluate (no arrays on disk).")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, _ in rs:
            w(f"| `{label[2:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
