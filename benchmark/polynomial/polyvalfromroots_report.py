"""Renders polyvalfromroots_results.md from a polyvalfromroots_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polyvalfromroots_numpy.py):
    python polyvalfromroots_report.py ns_vfr.tsv > polyvalfromroots_results.md
    python polyvalfromroots_report.py ns_vfr_1.tsv ns_vfr_2.tsv ... > polyvalfromroots_results.md
Several runs merge cell by cell, each side's MINIMUM time (an alternating NumPy / NumSharp schedule on a loaded host: a
background burst only ever adds time).

The C# runner has already checked every cell's result against NumPy's SHA-256 before timing it; this script only refuses
to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "F": "float64, a 1-D x and 1-D roots: 1K / 100K / 1M points x 3 / 10 / 30 roots",
    "T": "dtypes (x - r) at 100K points, 10 roots; the same-dtype pairs at 1K / 1M",
    "L": "x layouts at 100K points, 10 roots",
    "N": "N-D roots: tensor (the series of r's columns at every point), one series per point (tensor=False, r C and F)",
    "S": "a scalar x (Python float / complex, 0-d array): a 1-D r (a 0-d result) and r's columns (C and F)",
    "H": "float16 product forms: the slab (a narrow per root) and the reduce form (a float32 accumulation)",
    "C": "complex128 product forms: the slab (simd_cmul) and the reduce form (the contracted fallback product)",
    "E": "edges: no roots, one root, ten points",
    "R": "argument kinds: roots as a Python list of floats / ints, x as a Python list",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def read(path):
    """The cell rows of one runner TSV.

    Args:
        path: The TSV file.

    Returns:
        {label: (numsharp us, numpy us, check)}.
    """
    out = {}
    for line in open(path, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        # A cell label has a "/" (the per-section summary lines that follow the cells do not).
        if len(p) == 5 and "/" in p[0] and p[0].split("/")[0] in SECTIONS:
            out[p[0]] = (float(p[1]), float(p[2]), p[4])
    return out


def main():
    """Reads the runner TSVs (argv[1:]), merges them by per-cell minima, and prints the Markdown report; exits with an
    error on any byte mismatch.

    Returns:
        None.
    """
    runs = [read(p) for p in sys.argv[1:]]
    labels = list(runs[0])
    rows = []
    for label in labels:
        ns = min(r[label][0] for r in runs if label in r)
        npy = min(r[label][1] for r in runs if label in r)
        checks = {r[label][2] for r in runs if label in r}
        rows.append((label, ns, npy, npy / ns, "exact" if checks == {"exact"} else ",".join(sorted(checks))))
    bad = [r for r in rows if r[4] != "exact"]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells did not match NumPy's bytes, e.g. {bad[0]}")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0].split("/")[0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial.polynomial.polyvalfromroots (unit 6) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyvalfromroots_report.py` from `polyvalfromroots_bench.cs` runs. **NPY/NS =")
    w("NumPy time / NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was compared byte")
    w(f"for byte (SHA-256 of dtype, shape and data) against NumPy's before it was timed: all {len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently; C# in Release with")
    w("`DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up; best-of-rounds per side")
    if len(runs) > 1:
        w(f"and, over {len(runs)} alternating NumPy / NumSharp runs, each side's minimum per cell (a background burst on the")
        w("host only ever adds time).")
    else:
        w("in one run.")
    w("NumPy computes `np.prod(x - r, axis=0)`: an `x - r` temporary of nr times the result, then the reduction's nr")
    w("multiply passes (or its reduce loop over the roots). NumSharp runs one pass: each point reads its roots once and")
    w("writes its value once, the products in NumPy's own order and form.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    slow = [r for r in rows if r[3] < 1.5]
    if slow:
        w("Cells under 1.5×, and why:")
        w("")
        for label, ns, npy, ratio, _ in slow:
            if label == "E/r0/100k":
                # Measured 2026-10-18 (scratchpad ones_floor.cs and its NumPy twin): the identity fill is the whole call.
                w(f"- `{label}` ({ratio:.2f}×): with no roots both libraries only allocate the 100K-point result and write")
                w("  1.0 into it — NumSharp's `fill` alone takes 19.1 µs, NumPy's `np.ones(100000)` alone 18.6 µs — so")
                w("  NumPy's whole call (~22 µs) over that fill is the ceiling (~1.16×).")
            else:
                w(f"- `{label}` ({ratio:.2f}×): not analysed in this report.")
        w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, _ in rs:
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
