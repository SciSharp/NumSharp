"""NumPy 2.4.2 twin of polyeval_bench.cs — the numpy.polynomial evaluation family (U3) benchmark.

Writes data/polyeval/manifest.json (gitignored) — the cell list the C# side replays — then prints NumPy's
best-of-R per-call time for every cell (TSV: cell<TAB>us).

No array is written to disk: every input is generated by ONE exact formula both languages evaluate
bit-identically (integer arithmetic, one correctly rounded division, one subtraction — see gen()), and each
cell records the SHA-256 of NumPy's result bytes (+ dtype and shape), which the C# runner checks BEFORE it
times the cell. (The first version saved .npy inputs and references: ~5 GB for the 10M cells.)

Usage (from this directory; pin both sides with the same mask, never run them concurrently):
    set NS_PROBE_AFFINITY=0xF0
    python polyeval_numpy.py > numpy_times.tsv
    set DOTNET_TC_CallCountingDelayMs=0
    dotnet run -c Release --no-cache polyeval_bench.cs -- data/polyeval numpy_times.tsv > ns_all.tsv
    python polyeval_report.py ns_all.tsv > polyeval_results.md
POLYEVAL_ONLY=M/ (comma-separated label prefixes) restricts both sides to matching cells.

Sections (cell-label prefixes):
    E  the six bases, 1-D float64 coefficients, degree 3/10/30 x size 1K/100K/10M
    T  dtypes and mixed dtypes (every x dtype NumPy has, float16/float32/complex128 coefficients,
       the peeled float32-series-at-float64-x cases), all six bases @100K, plus 1K/10M spot cells
    L  x memory layouts (strided, reversed, transposed, F-order, broadcast, 2-D/3-D) @100K
    N  N-D coefficients: multi-series tensor=True, tensor=False (per-point series), coefficient layouts
    S  scalar x: Python scalars (weak) and 0-d arrays (strong) against 1-D and N-D series
    D  val2d / val3d / grid2d / grid3d / valnd
    M  the full mixed-dtype matrix at L1/L2-resident sizes (1K, 10K) — where NumPy's own loops are cheapest,
       and where the 100K-only T section once hid 227 cells below 1.5x
"""
import hashlib
import json
import os
import sys
import timeit
from pathlib import Path

os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")

import numpy as np  # noqa: E402
from numpy.polynomial import chebyshev as C  # noqa: E402
from numpy.polynomial import hermite as H  # noqa: E402
from numpy.polynomial import hermite_e as HE  # noqa: E402
from numpy.polynomial import laguerre as LG  # noqa: E402
from numpy.polynomial import legendre as L  # noqa: E402
from numpy.polynomial import polynomial as P  # noqa: E402
from numpy.polynomial import polyutils as PU  # noqa: E402

HERE = Path(__file__).resolve().parent
DATA = HERE / "data" / "polyeval"

MODULES = {"poly": P, "cheb": C, "leg": L, "lag": LG, "herm": H, "herme": HE}
MODNAME = {"poly": "polynomial", "cheb": "chebyshev", "leg": "legendre", "lag": "laguerre",
           "herm": "hermite", "herme": "hermite_e"}

CELLS = []


def pin_affinity():
    """Pin like the C# side (NS_PROBE_AFFINITY hex mask) through the shared benchmark_host helper."""
    sys.path.insert(0, str(HERE.parent / "scripts"))
    try:
        from benchmark_host import pin_current_process_from_env
        pin_current_process_from_env()
    except Exception as e:  # never fail the run over a host control
        print(f"# pin skipped: {e}", file=sys.stderr)


def gen(shape, dtype, seed):
    """The shared input formula: t_i = (i*7919 + seed*104729) mod 20011, value = t_i/10005.5 - 1.0 in [-1, 1).
    int dtypes take t_i mod 7 - 3 (unsigned: mod 4), bool t_i mod 2, complex (value(seed), value(seed+1000)).
    polyeval_bench.cs implements the identical formula; every step is exact or one correctly rounded op."""
    shape = tuple(shape)
    n = int(np.prod(shape)) if shape else 1
    i = np.arange(n, dtype=np.int64)
    t = (i * 7919 + seed * 104729) % 20011
    dt = np.dtype(dtype)
    if dt.kind == "b":
        v = (t % 2) == 1
    elif dt.kind == "u":
        v = (t % 4).astype(dt)
    elif dt.kind == "i":
        v = (t % 7 - 3).astype(dt)
    elif dt.kind == "c":
        t2 = (i * 7919 + (seed + 1000) * 104729) % 20011
        v = (t / 10005.5 - 1.0) + 1j * (t2 / 10005.5 - 1.0)
        v = v.astype(dt)
    else:
        v = (t / 10005.5 - 1.0).astype(dt)
    # np.array, not np.ascontiguousarray: the latter turns a 0-d array into a 1-element 1-D one.
    return np.array(np.asarray(v).reshape(shape))


def apply_view(a, transform):
    """The view grammar shared with the C# runner: 'slice:<numpy slice text>', 'T', 'F', 'bcast:d0,d1,...'."""
    if transform is None:
        return a
    if transform == "T":
        return a.T
    if transform == "F":
        return np.asfortranarray(a)
    if transform.startswith("slice:"):
        parts = []
        for tok in transform[len("slice:"):].split(","):
            tok = tok.strip()
            if ":" in tok:
                parts.append(slice(*[int(v) if v else None for v in tok.split(":")]))
            else:
                parts.append(int(tok))
        return a[tuple(parts)]
    if transform.startswith("bcast:"):
        return np.broadcast_to(a, tuple(int(v) for v in transform[len("bcast:"):].split(",")))
    raise ValueError(transform)


class G:
    """An array argument: generated base + optional view transform (materialized lazily, so a filtered-out
    cell never allocates its inputs)."""
    def __init__(self, shape, dtype="float64", seed=0, view=None):
        self.spec = {"shape": list(shape), "dtype": dtype, "seed": seed}
        if view:
            self.spec["view"] = view
        self._args = (shape, dtype, seed, view)
        self._array = None

    @property
    def array(self):
        if self._array is None:
            shape, dtype, seed, view = self._args
            self._array = apply_view(gen(shape, dtype, seed), view)
        return self._array


def digest(r):
    r = np.asarray(r)
    h = hashlib.sha256(np.ascontiguousarray(r).tobytes()).hexdigest()
    return {"dtype": r.dtype.name, "shape": [int(d) for d in r.shape], "sha256": h}


def loops_for(work):
    """(calls per round K, rounds R): enough calls per round to dwarf the timer, a single call at 10M."""
    if work >= 5_000_000:
        return 1, 3
    if work >= 200_000:
        return 3, 5
    if work >= 20_000:
        return 20, 7
    return 200, 9


ONLY = [p for p in os.environ.get("POLYEVAL_ONLY", "").split(",") if p]


def cell(label, base, kind, args, c, tensor=True, work=None):
    """Register one cell. args: G instances or ('weak', python_scalar); c: a G instance.
    POLYEVAL_ONLY=prefix[,prefix...] restricts the run (and the manifest) to matching labels."""
    if ONLY and not any(label.startswith(p) for p in ONLY):
        return
    mod = MODULES[base]
    specs, call_args = [], []
    for a in args:
        if isinstance(a, tuple) and a[0] == "weak":
            v = a[1]
            if isinstance(v, complex):
                specs.append({"weak": "complex", "re": v.real, "im": v.imag})
            elif isinstance(v, bool):
                specs.append({"weak": "bool", "value": v})
            elif isinstance(v, int):
                specs.append({"weak": "int", "value": v})
            else:
                specs.append({"weak": "float", "value": v})
            call_args.append(v)
        else:
            specs.append({"gen": a.spec})
            call_args.append(a.array)
    carr = c.array
    if kind == "val":
        fn = getattr(mod, base + "val")
        call = lambda: fn(call_args[0], carr, tensor=tensor)
    elif kind == "valnd":
        val = getattr(mod, base + "val")
        call = lambda: PU._valnd(val, carr, *call_args)
    else:
        fn = getattr(mod, base + kind)
        call = lambda: fn(*call_args, carr)
    ref = np.asarray(call())
    if work is None:
        work = max(ref.size, 1) * max(carr.shape[0], 1)
    k, r = loops_for(work)
    CELLS.append({"label": label, "module": MODNAME[base], "base": base, "kind": kind, "args": specs,
                  "c": c.spec, "tensor": tensor, "expect": digest(ref), "k": k, "r": r, "_call": call})


def build():
    bases = list(MODULES)
    # E: core float64 evaluation
    for b in bases:
        for deg in (3, 10, 30):
            for n in (1_000, 100_000, 10_000_000):
                if n == 10_000_000 and deg == 30:
                    continue
                cell(f"E/{b}/d{deg}/{n}", b, "val", [G((n,))], G((deg + 1,), seed=7))
    # T: dtypes @100K (degree 10), every basis
    pairs = [("float32", "float32"), ("float16", "float16"), ("complex128", "complex128"),
             ("float32", "float64"), ("float64", "float32"), ("float16", "float32"), ("float32", "float16"),
             ("float64", "float16"), ("int64", "float64"), ("int32", "float64"), ("int16", "float64"),
             ("int8", "float64"), ("uint8", "float64"), ("uint16", "float64"), ("uint32", "float64"),
             ("uint64", "float64"), ("bool", "float64"), ("float64", "complex128"), ("complex128", "float64"),
             ("float64", "int64"), ("int32", "float32")]
    for b in bases:
        for tx, tc in pairs:
            cell(f"T/{b}/{tx}-{tc}/100000", b, "val", [G((100_000,), tx, 1)], G((11,), tc, 7))
        for tx, tc in (("float32", "float32"), ("float16", "float16"), ("complex128", "complex128")):
            for n in (1_000, 10_000_000):
                cell(f"T/{b}/{tx}-{tc}/{n}", b, "val", [G((n,), tx, 1)], G((11,), tc, 7))
    # L: layouts @100K (degree 10)
    for b in bases:
        cell(f"L/{b}/strided2", b, "val", [G((200_000,), view="slice:::2")], G((11,), seed=7))
        cell(f"L/{b}/reversed", b, "val", [G((100_000,), view="slice:::-1")], G((11,), seed=7))
        cell(f"L/{b}/c2d", b, "val", [G((317, 317))], G((11,), seed=7))
        cell(f"L/{b}/transposed", b, "val", [G((317, 317), view="T")], G((11,), seed=7))
        cell(f"L/{b}/forder", b, "val", [G((317, 317), view="F")], G((11,), seed=7))
        cell(f"L/{b}/bcast", b, "val", [G((1_000,), view="bcast:100,1000")], G((11,), seed=7))
        cell(f"L/{b}/c3d", b, "val", [G((40, 50, 50))], G((11,), seed=7))
        cell(f"L/{b}/strided2d", b, "val", [G((317, 634), view="slice::,::2")], G((11,), seed=7))
        cell(f"L/{b}/f32strided", b, "val", [G((200_000,), "float32", view="slice:::2")], G((11,), "float32", 7))
    # N: N-D coefficients
    for b in bases:
        cell(f"N/{b}/tensor8x100k", b, "val", [G((100_000,))], G((11, 8), seed=7))
        cell(f"N/{b}/tensor64x1k", b, "val", [G((1_000,))], G((11, 64), seed=7))
        cell(f"N/{b}/perpoint100k", b, "val", [G((100_000,))], G((11, 100_000), seed=7), tensor=False)
        cell(f"N/{b}/bcastrows", b, "val", [G((1_000,))], G((11, 100, 1_000), seed=7), tensor=False)
        cell(f"N/{b}/tensorFc", b, "val", [G((10_000,))], G((8, 11), seed=7, view="T"), tensor=True)
        cell(f"N/{b}/c128perpoint", b, "val", [G((10_000,), "complex128")], G((11, 10_000), "complex128", 7), tensor=False)
    # S: scalar x
    for b in bases:
        cell(f"S/{b}/weakf/1d", b, "val", [("weak", 0.37)], G((11,), seed=7), work=11)
        cell(f"S/{b}/weaki/1d", b, "val", [("weak", 3)], G((11,), seed=7), work=11)
        cell(f"S/{b}/weakc/1d", b, "val", [("weak", 0.25 - 0.5j)], G((11,), "complex128", 7), work=11)
        cell(f"S/{b}/arr0d/1d", b, "val", [G(())], G((11,), seed=7), work=11)
        cell(f"S/{b}/weakf/f32", b, "val", [("weak", 0.37)], G((11,), "float32", 7), work=11)
        cell(f"S/{b}/weakf/cols100k", b, "val", [("weak", 0.37)], G((11, 100_000), seed=7))
        cell(f"S/{b}/arr0d/cols100k", b, "val", [G(())], G((11, 100_000), seed=7))
    # M: the mixed-dtype matrix at the sizes where NumPy's own loops are cheapest (L1/L2-resident): every
    # NumPy x dtype x every inexact coefficient dtype, as a 1-D series (@1K, @10K) and per point (@10K,
    # tensor=False: each point reads its own series, NumPy's best case — no broadcast, whole-row ufuncs).
    xdts = ["bool", "int8", "uint8", "int16", "uint16", "int32", "uint32", "int64", "uint64",
            "float16", "float32", "float64", "complex128"]
    for b in bases:
        for tx in xdts:
            for tc in ("float16", "float32", "float64", "complex128"):
                cell(f"M/{b}/{tx}-{tc}/1d1k", b, "val", [G((1_000,), tx, 1)], G((11,), tc, 7))
                cell(f"M/{b}/{tx}-{tc}/1d10k", b, "val", [G((10_000,), tx, 1)], G((11,), tc, 7))
                cell(f"M/{b}/{tx}-{tc}/pp10k", b, "val", [G((10_000,), tx, 1)], G((11, 10_000), tc, 7),
                     tensor=False)
    # D: 2-D / 3-D / N-D
    for b in bases:
        cell(f"D/{b}/val2d/100k", b, "val2d", [G((100_000,), seed=1), G((100_000,), seed=2)], G((5, 5), seed=7))
        cell(f"D/{b}/grid2d/300", b, "grid2d", [G((300,), seed=1), G((300,), seed=2)], G((5, 5), seed=7))
        cell(f"D/{b}/val3d/100k", b, "val3d", [G((100_000,), seed=1), G((100_000,), seed=2), G((100_000,), seed=3)],
             G((4, 4, 4), seed=7))
        cell(f"D/{b}/grid3d/50", b, "grid3d", [G((50,), seed=1), G((50,), seed=2), G((50,), seed=3)], G((4, 4, 4), seed=7))
        cell(f"D/{b}/valnd2/100k", b, "valnd", [G((100_000,), seed=1), G((100_000,), seed=2)], G((5, 5), seed=7))
        cell(f"D/{b}/val2d/1k", b, "val2d", [G((1_000,), seed=1), G((1_000,), seed=2)], G((5, 5), seed=7))
        cell(f"D/{b}/grid2d/weak", b, "grid2d", [("weak", 0.3), G((1_000,), seed=2)], G((5, 5), seed=7))


def main():
    pin_affinity()
    DATA.mkdir(parents=True, exist_ok=True)
    build()
    (DATA / "manifest.json").write_text(json.dumps([{k: v for k, v in c.items() if k != "_call"} for c in CELLS],
                                                   indent=1), encoding="utf-8")
    print("cell\tnumpy_us")
    for c in CELLS:
        call, k, r = c["_call"], c["k"], c["r"]
        call()   # warm
        best = min(timeit.repeat(call, number=k, repeat=r)) / k
        print(f"{c['label']}\t{best * 1e6:.3f}", flush=True)


if __name__ == "__main__":
    main()
