"""Renders polyinterp_results.md from a polyinterp_bench.cs run (the TSV it prints).

Usage (from this directory, after a full run of both sides — see polyinterp_numpy.py):
    python polyinterp_report.py ns_interp.tsv > polyinterp_results.md

The C# runner has already checked every cell's result against NumPy's SHA-256 before timing it; this script only refuses
to render a run that reports a mismatch, so a committed report is always a bit-exact one.
"""
import collections
import math
import platform
import sys

SECTIONS = {
    "T": "tanh(x) + 0.5 (a vector result: gemv) at degree 1 / 2 / 5 / 10 / 20 / 50 / 100 / 200 / 500 / 1000",
    "V": "[sin(x), cos(x)] stacked into a (deg + 1, 2) result (gemm) at degree 5 / 20 / 100 / 500",
    "C": "exp(1j*x) (a complex result: zgemv) at degree 5 / 20 / 100 / 500",
    "R": "result kinds at degree 20: a Python list, a Python float (the (21, 21) product), float32, int64",
    "A": "argument forms at degree 20: args as a tuple / a list / an ndarray; deg as an np.uint16 / a 0-d int64 array",
}


def icon(r):
    """The house NPY/NS status icon.

    Args:
        r: The NPY/NS ratio of a cell.

    Returns:
        ✅ at or above parity, 🟡 from 0.5, 🟠 from 0.2, 🔴 below.
    """
    return "✅" if r >= 1.0 else "🟡" if r >= 0.5 else "🟠" if r >= 0.2 else "🔴"


def main():
    """Reads the runner's TSV (argv[1]) and prints the Markdown report; exits with an error on any byte mismatch.

    Returns:
        None.
    """
    rows = []
    for line in open(sys.argv[1], encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        # A cell label has a "/" (the per-section summary lines that follow the cells do not).
        if len(p) == 5 and "/" in p[0] and p[0].split("/")[0] in SECTIONS:
            rows.append((p[0], float(p[1]), float(p[2]), float(p[3]), p[4]))
    bad = [r for r in rows if r[4] != "exact"]
    if bad:
        sys.exit(f"refusing to render: {len(bad)} cells did not match NumPy's bytes, e.g. {bad[0]}")

    by = collections.defaultdict(list)
    for r in rows:
        by[r[0].split("/")[0]].append(r)
    out = []
    w = out.append
    w("# numpy.polynomial chebinterpolate (U9) — NumSharp vs NumPy 2.4.2")
    w("")
    w("Generated by `benchmark/polynomial/polyinterp_report.py` from a `polyinterp_bench.cs` run. **NPY/NS = NumPy time /")
    w("NumSharp time — higher is better, > 1 means NumSharp is faster.** Every cell's result was compared byte for byte")
    w(f"(SHA-256 of dtype, shape and data) against NumPy's before it was timed: all {len(rows)} cells are bit-exact.")
    w("")
    w("Method: both sides pinned to the same two P-cores (`NS_PROBE_AFFINITY=0x14`), never concurrently, OpenBLAS at ONE")
    w("thread on both sides (NumPy under `OPENBLAS_NUM_THREADS=1`, NumSharp through `NumSharp.Interop.OpenBLAS`, the same")
    w("scipy-openblas build); C# in Release with `DOTNET_TC_CallCountingDelayMs=0` and a drained tier-1 warm-up;")
    w("best-of-rounds per side. Both sides time the whole call, the interpolated function included (a Python lambda on")
    w("NumPy's side, a C# delegate on NumSharp's). NumPy's time at low degrees is its Python statements (chebvander's loop")
    w("over the degree, np.dot's argument conversion, the two divisions); at high degrees the (deg + 1)**2 matrix dominates")
    w("both sides — chebvander writes it (NumPy row by row, a ufunc call per row; NumSharp in one kernel) and the product")
    w("reads it — so the ratio falls from ~16x at degree 100-200 toward the memory cost of that matrix.")
    w(f"Host: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}.")
    w("")
    w("| Section | Cells | min NPY/NS | geomean NPY/NS | Covers |")
    w("|---|---:|---:|---:|---|")
    allr = [r[3] for r in rows]
    for s in SECTIONS:
        rs = [r[3] for r in by.get(s, [])]
        if not rs:
            continue
        g = math.exp(sum(math.log(x) for x in rs) / len(rs))
        w(f"| {s} | {len(rs)} | {min(rs):.2f} | {g:.2f} | {SECTIONS[s]} |")
    g = math.exp(sum(math.log(x) for x in allr) / len(allr))
    w(f"| **all** | **{len(allr)}** | **{min(allr):.2f}** | **{g:.2f}** | |")
    w("")
    for s in SECTIONS:
        rs = by.get(s, [])
        if not rs:
            continue
        w(f"## {s} — {SECTIONS[s]}")
        w("")
        w("| Cell | NumSharp µs | NumPy µs | NPY/NS |")
        w("|---|---:|---:|---:|")
        for label, ns, npy, ratio, _ in rs:
            w(f"| `{label[len(s) + 1:]}` | {ns:,.3f} | {npy:,.3f} | {icon(ratio)} {ratio:.2f} |")
        w("")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
